# Callback function
class ModelCheckpoint:
    def __init__(self, save_path, monitor='val_loss', mode='min', min_delta=0.0):
        self.save_path = save_path
        self.monitor = monitor
        self.mode = mode
        self.min_delta = min_delta

        self.best_epoch = 0

        # ตรวจสอบ mode
        if mode == 'min':
            self.best_score = float('inf')
        elif mode == 'max':
            self.best_score = float('-inf')
        else:
            raise ValueError('mode must be "min" or "max"')

    def _is_improved(self, current):
        if self.mode == 'min':
            return current < self.best_score - self.min_delta
        else:
            # mode == 'max'
            return current > self.best_score + self.min_delta

    def on_epoch_end(self, model, optimizer, epoch, logs):
        current = logs.get(self.monitor)
        # ตรวจสอบ Current จาก Logs
        if current is None:
            raise ValueError(f'Monitor {self.monitor} not found in logs')

        if self._is_improved(current):
            print(f'[Logs] Epoch: {epoch + 1} {self.monitor} improved from {self.best_score:.4f} to {current:.4f}, saving model to {self.save_path}')
            self.best_score = current
            self.best_epoch = epoch + 1 # เพื่อไม่ให้การแสดงผลเริ่มที่ epoch 0

            save_model(
                save_path=self.save_path,
                model=model,
                epoch=epoch + 1,
                optimizer=optimizer,
                monitor=self.monitor,
                best_score=self.best_score
            )
        else:
            print(f'[Logs] Epoch: {epoch + 1} {self.monitor} did not improve from {self.best_score:.4f}')

class EarlyStopping:
    def __init__(self, patience=7, monitor='val_loss', mode='min', min_delta=0.0):
        self.patience = patience
        self.monitor = monitor
        self.mode = mode
        self.min_delta = min_delta

        self.counter = 0
        self.is_stop = False

        # ตรวจสอบ mode
        if mode == 'min':
            self.best_score = float('inf')
        elif mode == 'max':
            self.best_score = float('-inf')
        else:
            raise ValueError('mode must be "min" or "max"')

    def _is_improved(self, current):
        if self.mode == 'min':
            return current < self.best_score - self.min_delta
        else:
            # mode == 'max'
            return current > self.best_score + self.min_delta

    def on_epoch_end(self, model, optimizer, epoch, logs):
        current = logs.get(self.monitor)
        # ตรวจสอบ Current จาก Logs
        if current is None:
            raise ValueError(f'Monitor {self.monitor} not found in logs')

        if self._is_improved(current):
            self.best_score = current
            self.counter = 0 # Reset counter ใหม่
        else:
            self.counter += 1
            if self.counter >= self.patience:
                self.is_stop = True
                print(f'[Logs] Early stopping triggered at epoch {epoch + 1}')