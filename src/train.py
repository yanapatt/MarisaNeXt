import torch
from torch.utils.data import DataLoader
from torchmetrics.functional import accuracy, f1_score, precision, recall, specificity

import numpy as np
from time import time

from typing import Union, Optional, Tuple, Dict, Any
from collections import defaultdict
from pkbar import Kbar

from .utils import *

class Trainer:
    def __init__(self,
                 device: torch.device,
                 criterion: torch.nn.Module,
                 n_classes: Optional[int] = None,
                 task: str = 'multiclass',
                 average: str = 'macro',
                 max_grad_norm: float = 0.0,
                 ):
        self.device = device
        self.criterion = criterion
        self.n_classes = n_classes
        self.task = task
        self.average = average
        self.max_grad_norm = max_grad_norm

        assert self.task in ['binary', 'multiclass'], 'Task should be either binary or multiclass.'
        if self.task == 'multiclass':
            assert self.n_classes is not None and self.n_classes > 1, 'n_classes must be specified and > 1 for multiclass task.'

    @staticmethod
    def _perf_metrics(y_pred: torch.Tensor,
                      y_true: torch.Tensor,
                      n_classes: Optional[int] = None,
                      task: str = 'multiclass',
                      average: str = 'macro') -> Tuple[float, float, float, float, float]:
        """
            Performance metrics for classification tasks.
                - Accuracy : (TP + TN) / (TP + FP + TN + FN)
                - F1 Score : 2 * (precision * recall) / (precision + recall)
                - Precision : TP / (TP + FP)
                - Recall : TP / (TP + FN)
                - Specificity : TN / (TN + FP)
            Args:
                - y_pred (torch.Tensor): Predicted labels.
                - y_true (torch.Tensor): True labels.
                - n_classes (int, optional): Number of classes. Defaults to None.
                - task (str, optional): Task type. Defaults to 'multiclass'.
                - average (str, optional): Average type. Defaults to 'macro'.
            Returns:
                float(acc), float(f1), float(prec), float(rec), float(spec)
        """
        if task == 'multiclass' and y_true.ndim > 1 and y_true.size(1) > 1:
            y_true = torch.argmax(y_true, dim=1)

        if task == 'binary':
            if y_pred.ndim == 2 and y_pred.size(1) == 1:
                y_pred = y_pred.squeeze(dim=1)
            if y_true.ndim == 2 and y_true.size(1) == 1:
                y_true = y_true.squeeze(dim=1)
            y_true = y_true.long()

        if task == 'multiclass':
            acc = accuracy(y_pred, y_true, task=task, num_classes=n_classes) # average='micro' by default
            f1 = f1_score(y_pred, y_true, task=task, num_classes=n_classes, average=average)
            prec = precision(y_pred, y_true, task=task, num_classes=n_classes, average=average)
            rec = recall(y_pred, y_true, task=task, num_classes=n_classes, average=average)
            spec = specificity(y_pred, y_true, task=task, num_classes=n_classes, average=average)
        else: # 'binary'
            acc = accuracy(y_pred, y_true, task=task)
            f1 = f1_score(y_pred, y_true, task=task)
            prec = precision(y_pred, y_true, task=task)
            rec = recall(y_pred, y_true, task=task)
            spec = specificity(y_pred, y_true, task=task)

        return float(acc), float(f1), float(prec), float(rec), float(spec)

    def _process_labels(self, labels: torch.Tensor) -> torch.Tensor:
        if self.task == 'multiclass':
            labels = labels.long()
            if labels.ndim == 2: labels = labels.squeeze(1)
        else:
            labels = labels.float()
            if labels.ndim == 1: labels = labels.unsqueeze(1)
        return labels

    def _get_predictions(self, outputs: torch.Tensor) -> torch.Tensor:
        if self.task == 'multiclass':
            return torch.argmax(outputs, dim=1)
        else:
            probs = torch.sigmoid(outputs)
            preds = (probs > 0.5).float()
            if preds.ndim > 1: preds = preds.view(-1)
            return preds

    def train_epoch(self,
                         model: torch.nn.Module,
                         optimizer: torch.optim.Optimizer,
                         dataloader: DataLoader,
                         epoch: int,
                         total_epochs: int) -> Dict[str, float]:
        model.train()
        total_batches = len(dataloader)

        running_loss = 0.0
        total_samples = 0

        all_preds = []
        all_labels = []

        kbar = Kbar(target=total_batches, epoch=epoch, num_epochs=total_epochs, width=30, always_stateful=True)

        for i, (inputs, labels) in enumerate(dataloader):
            inputs = inputs.to(self.device, non_blocking=True)
            labels = self._process_labels(labels.to(self.device, non_blocking=True))

            optimizer.zero_grad(set_to_none=True)
            outputs = model(inputs)

            loss = self.criterion(outputs, labels)
            loss.backward()

            if self.max_grad_norm > 0:
                torch.nn.utils.clip_grad_norm_(model.parameters(), self.max_grad_norm)
            optimizer.step()

            batch_size = inputs.size(0)
            running_loss += loss.item() * batch_size
            total_samples += batch_size

            b_preds = self._get_predictions(outputs)

            if self.task == 'binary' and labels.ndim > 1:
                labels = labels.view(-1)

            all_preds.append(b_preds.detach().cpu())
            all_labels.append(labels.detach().cpu())

            kbar.update(i, values=[('loss', loss.item()), ('lr', optimizer.param_groups[0]['lr'])])

        if total_samples == 0: return {key: 0.0 for key in ['loss', 'accuracy', 'f1', 'precision', 'recall', 'specificity', 'lr']}

        e_preds = torch.cat(all_preds)
        e_labels = torch.cat(all_labels)
        e_loss = running_loss / total_samples
        e_acc, e_f1, e_prec, e_rec, e_spec = self._perf_metrics(e_preds, e_labels, self.n_classes, self.task, self.average)
        e_lr = optimizer.param_groups[0]['lr']

        kbar.add(1, values=[
            ('loss', e_loss), ('acc', e_acc), ('f1', e_f1), ('prec', e_prec),
            ('recall', e_rec), ('spec', e_spec), ('lr', e_lr)
        ])

        return {'loss': e_loss, 'accuracy': e_acc, 'f1': e_f1, 'precision': e_prec, 'recall': e_rec, 'specificity': e_spec, 'lr': e_lr}

    def evaluate_epoch(self, model: torch.nn.Module, dataloader: DataLoader, verbose: int = 0) -> Dict[str, float]:
        assert verbose in [0, 1], 'Verbose should be either 0 or 1.'

        model.eval()
        total_batches = len(dataloader)

        running_loss = 0.0
        total_samples = 0

        all_preds = []
        all_labels = []

        kbar = Kbar(target=total_batches, width=30, always_stateful=True) if verbose == 1 else None

        with torch.inference_mode():
            for i, (inputs, labels) in enumerate(dataloader):
                inputs = inputs.to(self.device, non_blocking=True)
                labels = self._process_labels(labels.to(self.device, non_blocking=True))

                outputs = model(inputs)
                loss = self.criterion(outputs, labels)

                batch_size = inputs.size(0)
                running_loss += loss.item() * batch_size
                total_samples += batch_size

                b_preds = self._get_predictions(outputs)
                if self.task == 'binary' and labels.ndim > 1:
                    labels = labels.view(-1)

                all_preds.append(b_preds.detach().cpu())
                all_labels.append(labels.detach().cpu())

                if kbar:
                    kbar.update(i, values=[('loss', loss.item())])

        if total_samples == 0: return {key: 0.0 for key in ['loss', 'accuracy', 'f1', 'precision', 'recall', 'specificity']}

        e_preds = torch.cat(all_preds)
        e_labels = torch.cat(all_labels)
        e_loss = running_loss / total_samples
        e_acc, e_f1, e_prec, e_rec, e_spec = self._perf_metrics(e_preds, e_labels, self.n_classes, self.task, self.average)

        if kbar:
            kbar.add(1, values=[
                ('loss', e_loss), ('acc', e_acc), ('f1', e_f1),
                ('prec', e_prec), ('recall', e_rec), ('spec', e_spec)
            ])

        return {'loss': e_loss, 'accuracy': e_acc, 'f1': e_f1, 'precision': e_prec, 'recall': e_rec, 'specificity': e_spec}

    def fit(self,
            train_loader: DataLoader,
            val_loader: DataLoader,
            model: torch.nn.Module,
            optimizer: torch.optim.Optimizer,
            epochs: int,
            callbacks: Optional[list] = None,
            scheduler: Optional[Any] = None,
            save_path: Optional[str] = None
            ) -> Dict[str, list]:

        if callbacks is None:
            callbacks = []
        elif not isinstance(callbacks, list):
            callbacks = [callbacks]

        history = defaultdict(list)
        start_time = time()

        for epoch in range(epochs):
            train_metrics = self.train_epoch(model, optimizer, train_loader, epoch, epochs)
            val_metrics = self.evaluate_epoch(model, val_loader, verbose=0)

            logs = train_metrics.copy()
            for key, value in val_metrics.items():
                logs[f'val_{key}'] = value

            if scheduler:
                scheduler.step()

            history['epoch'].append(epoch + 1)
            for key, value in logs.items():
                val = value.item() if hasattr(value, 'item') else value
                history[key].append(val)

            print(f"Epoch {epoch+1}/{epochs} | val_loss: {logs['val_loss']:.4f} - val_acc: {logs['val_accuracy']:.4f} - val_f1: {logs['val_f1']:.4f} - val_prec: {logs['val_precision']:.4f} - val_rec: {logs['val_recall']:.4f} - val_spec: {logs['val_specificity']:.4f}")

            stop_signal = False
            for callback in callbacks:
                callback.on_epoch_end(model, optimizer, epoch, logs)
                if getattr(callback, 'is_stop', False):
                    stop_signal = True

            if stop_signal:
                break

        duration = time() - start_time
        print('-' * 100)
        print(f'[Logs] Training completed in {duration:.2f} seconds')

        for callback in callbacks:
            if callback.__class__.__name__ == 'ModelCheckpoint':
                print(f'[Logs] Best model found at epoch {callback.best_epoch} ({callback.monitor}: {callback.best_score:.4f})')

        if save_path:
            save_model(
                save_path=save_path,
                model=model,
                optimizer=optimizer,
                epoch=epochs
            )
            print(f'[Logs] Model final weights has been saved to {save_path}')

        return dict(history)

    def predict(self, model: torch.nn.Module, dataloader: DataLoader,
                timer_report_dict: bool = False, verbose: int = 1) -> Union[np.ndarray, Tuple[np.ndarray, Dict[str, float]]]:

        assert verbose in [0, 1], 'Verbose should be either 0 or 1.'
        total_batches = len(dataloader)
        if total_batches == 0:
            return (np.array([]), {}) if timer_report_dict else np.array([])

        model.eval()
        all_probs = []

        running_time_ms = 0.0
        total_inference_samples = 0

        use_cuda = self.device.type == 'cuda'
        if use_cuda:
            start_event = torch.cuda.Event(enable_timing=True)
            end_event = torch.cuda.Event(enable_timing=True)

        kbar = Kbar(target=total_batches, width=30, always_stateful=True) if verbose == 1 else None

        with torch.inference_mode():
            for i, batch in enumerate(dataloader):
                if isinstance(batch, (list, tuple)):
                    inputs = batch[0]
                else:
                    inputs = batch

                inputs = inputs.to(self.device, non_blocking=True)
                batch_size = inputs.size(0)
                total_inference_samples += batch_size

                if use_cuda:
                    start_event.record()
                else:
                    iter_start = time()

                outputs = model(inputs)

                if use_cuda:
                    end_event.record()
                    torch.cuda.synchronize()
                    iter_ms = start_event.elapsed_time(end_event)
                else:
                    iter_end = time()
                    iter_ms = (iter_end - iter_start) * 1000

                running_time_ms += iter_ms

                if self.task == 'multiclass':
                    probs = torch.softmax(outputs, dim=1)
                else: # 'binary'
                    probs = torch.sigmoid(outputs)
                    if probs.ndim > 1:
                        probs = probs.view(-1)

                all_probs.append(probs.detach().cpu())

                if kbar:
                    kbar.update(i)

        if kbar:
            kbar.add(1)

        out_probs = torch.cat(all_probs).numpy()

        if timer_report_dict:
            # Latency (ms/batch)
            latency_batch = running_time_ms / total_batches

            # Latency (ms/sample)
            latency_sample = running_time_ms / total_inference_samples

            # Throughput (samples/s)
            total_seconds = running_time_ms / 1000
            throughput = total_inference_samples / total_seconds

            timer_final_report = {
                'infer_latency': latency_batch,
                'infer_latency_sample': latency_sample,
                'infer_throughput': throughput,
                'infer_total_samples': total_inference_samples
            }

            if verbose == 1:
                print(f"\n[Inference Report] Latency: {latency_batch:.2f} ms/batch | Throughput: {throughput:.2f} samples/sec")
            return out_probs, timer_final_report

        return out_probs