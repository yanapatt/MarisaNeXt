class Trainer:
    def __init__(self,
                 device: torch.device,
                 criterion: torch.nn.Module,
                 n_classes: Optional[int] = None,
                 task: str = 'multiclass',
                 average: str = 'macro',
                 max_grad_norm: float = 0.0,
                 ):
        """
            This class is used to train a model (baseline) for train test validation dataset.
            Initial Args (Needs):
                - device (torch.device): Device to use for training.
                - criterion (torch.nn.Module): Loss function.
                - n_classes (int, optional): Number of classes. Defaults to None.
                - task (str, optional): Task type. Defaults to 'multiclass'. Valid values: 'binary', 'multiclass'.
                - average (str, optional): Average type. Defaults to 'macro'.
                - max_grad_norm (float, optional): Maximum gradient norm. Defaults to 0.0.
        """
        self.device = device
        self.criterion = criterion
        self.n_classes = n_classes
        self.task = task
        self.average = average
        self.max_grad_norm = max_grad_norm

        assert self.task in ['binary', 'multiclass'], 'Task should be either binary or multiclass.'
        if self.task == 'multiclass':
            assert self.n_classes is not None and self.n_classes > 1, 'n_classes must be specified and > 1 for multiclass task.'

    @staticmethod
    def _perf_metrics(y_pred: torch.Tensor,
                      y_true: torch.Tensor,
                      n_classes: Optional[int] = None,
                      task: str = 'multiclass',
                      average: str = 'macro') -> Tuple[float, float, float, float]:
        """
            Performance metrics for classification tasks.
                - Accuracy : (TP + TN) / (TP + FP + TN + FN)
                - F1 Score : 2 * (precision * recall) / (precision + recall)
                - Precision : TP / (TP + FP)
                - Recall : TP / (TP + FN)
            Args:
                - y_pred (torch.Tensor): Predicted labels.
                - y_true (torch.Tensor): True labels.
                - n_classes (int, optional): Number of classes. Defaults to None.
                - task (str, optional): Task type. Defaults to 'multiclass'.
                - average (str, optional): Average type. Defaults to 'macro'.
            Returns:
                float(acc), float(f1), float(prec), float(rec), float(spec)
        """
        if task == 'multiclass' and y_true.ndim > 1 and y_true.size(1) > 1:
            y_true = torch.argmax(y_true, dim=1)

        if task == 'binary':
            if y_pred.ndim == 2 and y_pred.size(1) == 1:
                y_pred = y_pred.squeeze(dim=1)
            if y_true.ndim == 2 and y_true.size(1) == 1:
                y_true = y_true.squeeze(dim=1)
            y_true = y_true.long()

        if task == 'multiclass':
            acc = accuracy(y_pred, y_true, task=task, num_classes=n_classes) # average='micro' by default
            f1 = f1_score(y_pred, y_true, task=task, num_classes=n_classes, average=average)
            prec = precision(y_pred, y_true, task=task, num_classes=n_classes, average=average)
            rec = recall(y_pred, y_true, task=task, num_classes=n_classes, average=average)
        else: # 'binary'
            acc = accuracy(y_pred, y_true, task=task)
            f1 = f1_score(y_pred, y_true, task=task)
            prec = precision(y_pred, y_true, task=task)
            rec = recall(y_pred, y_true, task=task)

        return float(acc), float(f1), float(prec), float(rec)

    def _process_labels(self, labels: torch.Tensor) -> torch.Tensor:
        """
            The private method to process labels.
            Args:
                - labels (torch.Tensor): Labels to process.
            Returns:
                torch.Tensor: Processed labels.
        """
        if self.task == 'multiclass':
            labels = labels.long()
            if labels.ndim == 2: labels = labels.squeeze(1)
        else:
            labels = labels.float()
            if labels.ndim == 1: labels = labels.unsqueeze(1)
        return labels

    def _get_predictions(self, outputs: torch.Tensor) -> torch.Tensor:
        """
            The private method to get predictions.
            Args:
                - outputs (torch.Tensor): Outputs to process.
            Returns:
                torch.Tensor: Processed outputs.
        """
        if self.task == 'multiclass':
            return torch.argmax(outputs, dim=1)
        else:
            probs = torch.sigmoid(outputs)
            preds = (probs > 0.5).float()
            if preds.ndim > 1: preds = preds.view(-1)
            return preds

    def train_epoch(self,
                    model: torch.nn.Module,
                    optimizer: torch.optim.Optimizer,
                    dataloader: DataLoader,
                    epoch: int,
                    total_epochs: int
                    ) -> Dict[str, float]:
        """
            The public method to train a model for one epoch.
            Args:
                - model (torch.nn.Module): Model to train.
                - optimizer (torch.optim.Optimizer): Optimizer to use.
                - dataloader (DataLoader): Dataloader to use.
                - epoch (int): Current epoch.
                - total_epochs (int): Total number of epochs.
            Returns:
                Dict[str, float]: Training metrics.
        """
        model.train()
        total_batches = len(dataloader)

        running_loss = 0.0
        total_samples = 0

        all_preds = []
        all_labels = []

        kbar = Kbar(target=total_batches, epoch=epoch, num_epochs=total_epochs, width=30, always_stateful=True)

        for i, (inputs, labels) in enumerate(dataloader):
            inputs = inputs.to(self.device, non_blocking=True)
            labels = self._process_labels(labels.to(self.device, non_blocking=True))

            optimizer.zero_grad(set_to_none=True)
            outputs = model(inputs)

            loss = self.criterion(outputs, labels)
            loss.backward()

            if self.max_grad_norm > 0:
                torch.nn.utils.clip_grad_norm_(model.parameters(), self.max_grad_norm)
            optimizer.step()

            batch_size = inputs.size(0)
            running_loss += loss.item() * batch_size
            total_samples += batch_size

            b_preds = self._get_predictions(outputs)

            if self.task == 'binary' and labels.ndim > 1:
                labels = labels.view(-1)

            all_preds.append(b_preds.detach().cpu())
            all_labels.append(labels.detach().cpu())

            kbar.update(i, values=[('loss', loss.item()), ('lr', optimizer.param_groups[0]['lr'])])

        if total_samples == 0: return {key: 0.0 for key in ['loss', 'accuracy', 'f1', 'precision', 'recall', 'lr']}

        e_preds = torch.cat(all_preds)
        e_labels = torch.cat(all_labels)
        e_loss = running_loss / total_samples
        e_acc, e_f1, e_prec, e_rec = self._perf_metrics(e_preds, e_labels, self.n_classes, self.task, self.average)
        e_lr = optimizer.param_groups[0]['lr']

        kbar.add(1, values=[
            ('loss', e_loss), ('accuracy', e_acc), ('f1', e_f1), ('precision', e_prec),
            ('recall', e_rec), ('lr', e_lr)
        ])

        return {'loss': e_loss, 'accuracy': e_acc, 'f1': e_f1, 'precision': e_prec, 'recall': e_rec, 'lr': e_lr}

    def evaluate_epoch(self,
                       model: torch.nn.Module,
                       dataloader: DataLoader,
                       verbose: int = 0
                       ) -> Dict[str, float]:
        """
            The public method to evaluate a model for one epoch.
            Args:
                - model (torch.nn.Module): Model to evaluate.
                - dataloader (DataLoader): Dataloader to use.
                - verbose (int, optional): Verbosity level (0 : None, 1 : Visible)
            Returns:
                Dict[str, float]: Evaluation metrics.
        """
        assert verbose in [0, 1], 'Verbose should be either 0 or 1.'

        model.eval()
        total_batches = len(dataloader)

        running_loss = 0.0
        total_samples = 0

        all_preds = []
        all_labels = []

        kbar = Kbar(target=total_batches, width=30, always_stateful=True) if verbose == 1 else None

        with torch.inference_mode():
            for i, (inputs, labels) in enumerate(dataloader):
                inputs = inputs.to(self.device, non_blocking=True)
                labels = self._process_labels(labels.to(self.device, non_blocking=True))

                outputs = model(inputs)
                loss = self.criterion(outputs, labels)

                batch_size = inputs.size(0)
                running_loss += loss.item() * batch_size
                total_samples += batch_size

                b_preds = self._get_predictions(outputs)
                if self.task == 'binary' and labels.ndim > 1:
                    labels = labels.view(-1)

                all_preds.append(b_preds.detach().cpu())
                all_labels.append(labels.detach().cpu())

                if kbar:
                    kbar.update(i, values=[('loss', loss.item())])

        if total_samples == 0: return {key: 0.0 for key in ['loss', 'accuracy', 'f1', 'precision', 'recall']}

        e_preds = torch.cat(all_preds)
        e_labels = torch.cat(all_labels)
        e_loss = running_loss / total_samples
        e_acc, e_f1, e_prec, e_rec = self._perf_metrics(e_preds, e_labels, self.n_classes, self.task, self.average)

        if kbar:
            kbar.add(1, values=[
                ('loss', e_loss), ('accuracy', e_acc), ('f1', e_f1),
                ('precision', e_prec), ('recall', e_rec)
            ])

        return {'loss': e_loss, 'accuracy': e_acc, 'f1': e_f1, 'precision': e_prec, 'recall': e_rec}

    def fit(self,
            train_loader: DataLoader,
            val_loader: DataLoader,
            model: torch.nn.Module,
            optimizer: torch.optim.Optimizer,
            epochs: int,
            callbacks: Optional[list] = None,
            scheduler: Optional[Any] = None,
            save_path: Optional[str] = None
            ) -> Dict[str, list]:
        """
            The public method to train and evaluate a model for multiple epochs.
            Args:
                - train_loader (DataLoader): Training dataloader.
                - val_loader (DataLoader): Validation dataloader.
                - model (torch.nn.Module): Model to train.
                - optimizer (torch.optim.Optimizer): Optimizer to use.
                - epochs (int): Number of epochs to train (max epochs).
                - callbacks (list, optional): List of callbacks to use. Defaults to None.
                - scheduler (Any, optional): Scheduler to use. Defaults to None.
                - save_path (str, optional): Path to save the model. Defaults to None.
            Returns:
                - Dict[str, list]: Training history.
        """

        if callbacks is None:
            callbacks = []
        elif not isinstance(callbacks, list):
            callbacks = [callbacks]

        history = defaultdict(list)
        start_time = time()

        for epoch in range(epochs):
            train_metrics = self.train_epoch(model, optimizer, train_loader, epoch, epochs)
            val_metrics = self.evaluate_epoch(model, val_loader, verbose=0)

            logs = train_metrics.copy()
            for key, value in val_metrics.items():
                logs[f'val_{key}'] = value

            if scheduler:
                scheduler.step()

            history['epoch'].append(epoch + 1)
            for key, value in logs.items():
                val = value.item() if hasattr(value, 'item') else value
                history[key].append(val)

            print(f"Epoch {epoch+1}/{epochs} | val_loss: {logs['val_loss']:.4f} - val_accuracy: {logs['val_accuracy']:.4f} - val_f1: {logs['val_f1']:.4f} - val_precision: {logs['val_precision']:.4f} - val_recall: {logs['val_recall']:.4f}")

            stop_signal = False
            for callback in callbacks:
                callback.on_epoch_end(model, optimizer, epoch, logs)
                if getattr(callback, 'is_stop', False):
                    stop_signal = True

            if stop_signal:
                break

        duration = time() - start_time
        print('-' * 100)
        print(f'[Logs] Training completed in {duration:.2f} seconds')

        for callback in callbacks:
            if callback.__class__.__name__ == 'ModelCheckpoint':
                print(f'[Logs] Best model found at epoch {callback.best_epoch} ({callback.monitor}: {callback.best_score:.4f})')

        if save_path:
            save_model(
                save_path=save_path,
                model=model,
                optimizer=optimizer,
                epoch=epochs
            )
            print(f'[Logs] Model final weights has been saved to {save_path}')

        return dict(history)

    def predict(self,
                model: torch.nn.Module,
                dataloader: DataLoader,
                timer_report_dict: bool = False,
                verbose: int = 1
                ) -> Union[np.ndarray, Tuple[np.ndarray, Dict[str, float]]]:
        """
            The public method to predict using a model.
            Args:
                - model (torch.nn.Module): Model to use.
                - dataloader (DataLoader): Dataloader to use.
                - timer_report_dict (bool, optional): Whether to report timer report. Defaults to False.
                - verbose (int, optional): Verbosity level (0 : None, 1 : Visible)
            Returns:
                - np.ndarray: Predictions (For used on classification report, correct_predict, incorrect_predict).
        """

        assert verbose in [0, 1], 'Verbose should be either 0 or 1.'
        total_batches = len(dataloader)
        if total_batches == 0:
            return (np.array([]), {}) if timer_report_dict else np.array([])

        model.eval()
        all_probs = []

        running_time_ms = 0.0
        total_inference_samples = 0

        use_cuda = self.device.type == 'cuda'
        if use_cuda:
            start_event = torch.cuda.Event(enable_timing=True)
            end_event = torch.cuda.Event(enable_timing=True)

        kbar = Kbar(target=total_batches, width=30, always_stateful=True) if verbose == 1 else None

        with torch.inference_mode():
            for i, batch in enumerate(dataloader):
                if isinstance(batch, (list, tuple)):
                    inputs = batch[0]
                else:
                    inputs = batch

                inputs = inputs.to(self.device, non_blocking=True)
                batch_size = inputs.size(0)
                total_inference_samples += batch_size

                if use_cuda:
                    start_event.record()
                else:
                    iter_start = time()

                outputs = model(inputs)

                if use_cuda:
                    end_event.record()
                    torch.cuda.synchronize()
                    iter_ms = start_event.elapsed_time(end_event)
                else:
                    iter_end = time()
                    iter_ms = (iter_end - iter_start) * 1000

                running_time_ms += iter_ms

                if self.task == 'multiclass':
                    probs = torch.softmax(outputs, dim=1)
                else: # 'binary'
                    if outputs.shape[1] == 1:
                        probs = torch.sigmoid(outputs).view(-1)
                    else:
                        probs = torch.softmax(outputs, dim=1)

                all_probs.append(probs.detach().cpu())

                if kbar:
                    kbar.update(i)

        if kbar:
            kbar.add(1)

        out_probs = torch.cat(all_probs).numpy()

        if timer_report_dict:
            # Latency (ms/batch)
            latency_batch = running_time_ms / total_batches

            # Latency (ms/sample)
            latency_sample = running_time_ms / total_inference_samples

            # Throughput (samples/s)
            total_seconds = running_time_ms / 1000
            throughput = total_inference_samples / total_seconds

            timer_final_report = {
                'infer_latency': latency_batch,
                'infer_latency_sample': latency_sample,
                'infer_throughput': throughput,
                'infer_total_samples': total_inference_samples
            }

            if verbose == 1:
                print(f"\n[Inference Report] Latency: {latency_batch:.2f} ms/batch | Throughput: {throughput:.2f} samples/sec")
            return out_probs, timer_final_report

        return out_probs

class KFoldTrainer(Trainer):
    def __init__(self,
                 n_splits: int = 5,
                 shuffle: bool = True,
                 random_state: int = 42,
                 model_name: str = 'model',
                 dataset_name: str = 'dataset',
                 base_dir: str = './kfold_experiments',
                 first_metric: str = 'accuracy',
                 first_metric_mode: str = 'max',
                 secondary_metric: Optional[str] = None,
                 secondary_metric_mode: Optional[str] = None,
                 **kwargs
                 ):
        super().__init__(**kwargs)
        """
            This class inheritance from Trainer class.
            For training model with k-fold cross validation.
            Inital Args:
                - n_splits (int, optional): Number of splits. Defaults to 5.
                - shuffle (bool, optional): Whether to shuffle the data. Defaults to True.
                - random_state (int, optional): Random state. Defaults to 42.
                - model_name (str, optional): Name of the model. Defaults to 'model'.
                - dataset_name (str, optional): Name of the dataset. Defaults to 'dataset'.
                - base_dir (str, optional): Base directory to save the results. Defaults to './kfold_experiments'.
                - first_metric (str, optional): Metric to monitor. Defaults to 'accuracy' on validation set.
                - first_metric_mode (str, optional): Mode to monitor. Defaults to 'max' on validation set.
                - secondary_metric (str, optional): Secondary metric to monitor. Defaults to None on validation set.
                - secondary_metric_mode (str, optional): Secondary metric mode to monitor. Defaults to None on validation set.
                !!**kwargs: Keyword arguments to pass to the Trainer class (Mother class).!!
        """
        self.n_splits = n_splits
        self.shuffle = shuffle
        self.random_state = random_state
        self.model_name = model_name
        self.dataset_name = dataset_name
        self.base_dir = base_dir
        self.first_metric = first_metric
        self.first_metric_mode = first_metric_mode
        self.secondary_metric = secondary_metric
        self.secondary_metric_mode = secondary_metric_mode

        self.best_fold_num = None
        self.best_primary_val = float('inf') if first_metric_mode == 'min' else float('-inf')

        if self.secondary_metric:
            assert self.secondary_metric_mode in ['min', 'max'], "secondary_metric_mode must be 'min' or 'max'"
            self.best_secondary_val = float('inf') if self.secondary_metric_mode == 'min' else float('-inf')
        else:
            self.best_secondary_val = None

        self._make_directories()

    def _make_directories(self):
        """
            The private method to make directories.
            Returns:
                None
        """
        os.makedirs(f"{self.base_dir}/summary", exist_ok=True)
        os.makedirs(f"{self.base_dir}/ensemble", exist_ok=True)
        for fold in range(1, self.n_splits + 1):
            os.makedirs(f"{self.base_dir}/fold_{fold}", exist_ok=True)
        print(f"[Logs] Setup directories at '{self.base_dir}' successfully.")

    def _get_fold_indices(self, labels: np.ndarray) -> List[Tuple[np.ndarray, np.ndarray]]:
        """
            The private method to get fold indices.
            Args:
                - labels (np.ndarray): Labels to split.
            Returns:
                - List[Tuple[np.ndarray, np.ndarray]]: Fold indices.
        """
        skf = StratifiedKFold(n_splits=self.n_splits, shuffle=self.shuffle, random_state=self.random_state)
        return list(skf.split(np.zeros(len(labels)), labels))

    def fit_kfold(self,
                  train_dataset: torch.utils.data.Dataset,
                  val_dataset: torch.utils.data.Dataset,
                  labels: np.ndarray,
                  model_fn: Callable[[], torch.nn.Module],
                  optimizer_fn: Callable[[torch.nn.Module], torch.optim.Optimizer],
                  epochs: int,
                  dataloader_kwargs: dict,
                  callbacks_fn: Optional[Callable[[int, str], list]] = None,
                  scheduler_fn: Optional[Callable[[torch.optim.Optimizer], Any]] = None
                  ) -> Dict[str, Dict[str, list]]:
        """
            The public method to fit the model with k-fold cross validation.
            Args:
                - train_dataset (torch.utils.data.Dataset): Training dataset.
                - val_dataset (torch.utils.data.Dataset): Validation dataset.
                - labels (np.ndarray): Labels to split.
                - model_fn (Callable[[], torch.nn.Module]): Model
                - optimizer_fn (Callable[[torch.nn.Module], torch.optim.Optimizer]): Optimizer
                - epochs (int): Number of epochs to train.
                - dataloader_kwargs (dict): Keyword arguments to pass to the dataloader
                - callbacks_fn (Optional[Callable[[int, str], list]], optional): Callbacks to use. Defaults to None.
                - scheduler_fn (Optional[Callable[[torch.optim.Optimizer], Any]], optional): Scheduler to use. Defaults to None.
                Returns:
                - Dict[str, Dict[str, list]]: History of the model.
        """
        print(f"{'='*100}")
        print(f"Starting Stratified {self.n_splits}-Fold Cross Validation")
        print(f"{'='*100}\n")

        fold_histories = {}
        fold_indices = self._get_fold_indices(labels)

        for fold, (train_idx, val_idx) in enumerate(fold_indices):
            fold_num = fold + 1
            fold_dir = f"{self.base_dir}/fold_{fold_num}"
            print(f"{'-'*45} FOLD {fold_num}/{self.n_splits} {'-'*45}")

            train_sub = Subset(train_dataset, train_idx)
            val_sub = Subset(val_dataset, val_idx)

            train_loader = DataLoader(train_sub, shuffle=True, **dataloader_kwargs)
            val_loader = DataLoader(val_sub, shuffle=False, **dataloader_kwargs)

            model = model_fn().to(self.device)
            optimizer = optimizer_fn(model)
            scheduler = scheduler_fn(optimizer) if scheduler_fn else None

            callbacks = callbacks_fn(fold_num, fold_dir) if callbacks_fn else []
            save_path = f"{fold_dir}/{self.model_name}_{self.dataset_name}_final_weight.pth"

            history = self.fit(
                train_loader=train_loader,
                val_loader=val_loader,
                model=model,
                optimizer=optimizer,
                epochs=epochs,
                callbacks=callbacks,
                scheduler=scheduler,
                save_path=save_path
            )

            fold_histories[f'fold_{fold_num}'] = history
            fold_training_history_path = f"{fold_dir}/fold_{fold_num}_training_history.csv"
            pd.DataFrame(history).to_csv(fold_training_history_path, index=False)

        print(f"\n{'='*100}")
        print(f"Stratified {self.n_splits}-Fold Cross Validation Completed!")
        print(f"{'='*100}")

        kfold_training_history_path = f"{self.base_dir}/summary/kfold_training_history.csv"
        pd.DataFrame(fold_histories).to_csv(kfold_training_history_path, index=False)
        return fold_histories

    def evaluate_kfold(self,
                       val_dataset: torch.utils.data.Dataset,
                       labels: np.ndarray,
                       dataloader_kwargs: dict,
                       model_fn: Callable[[], torch.nn.Module],
                       weight_type: str = 'best'
                       ) -> pd.DataFrame:
        """
            The public method to evaluate the model with k-fold cross validation.
            Args:
                - val_dataset (torch.utils.data.Dataset): Validation dataset.
                - labels (np.ndarray): Labels to split.
                - dataloader_kwargs (dict): Keyword arguments to pass to the dataloader
                - model_fn (Callable[[], torch.nn.Module]): Model
                - weight_type (str, optional): Weight type to use. Defaults to 'best' (Valid on 'best' or 'final').
            Returns:
                - pd.DataFrame: Evaluation results.
        """
        assert weight_type in ['best', 'final'], 'weight_type should be either best or final.'

        print(f"{'='*100}")
        print(f"Evaluating {self.n_splits}-Fold Models on their respective Validation Sets ({weight_type.upper()} weights)")
        print(f"{'='*100}\n")

        fold_indices = self._get_fold_indices(labels)
        all_fold_metrics = []

        # Reset counter every called evalutate_kfold
        self.best_fold_num = None
        self.best_primary_val = float('inf') if self.first_metric_mode == 'min' else float('-inf')
        if self.secondary_metric:
            self.best_secondary_val = float('inf') if self.secondary_metric_mode == 'min' else float('-inf')

        for fold, (_, val_idx) in enumerate(fold_indices):
            fold_num = fold + 1
            fold_dir = f"{self.base_dir}/fold_{fold_num}"

            val_sub = Subset(val_dataset, val_idx)
            val_loader = DataLoader(val_sub, shuffle=False, **dataloader_kwargs)

            model = model_fn().to(self.device)
            weight_path = f"{fold_dir}/{self.model_name}_{self.dataset_name}_{weight_type}_weight.pth"
            load_model(save_path=weight_path, model=model, optimizer=None, device=self.device)

            print(f"[*] Evaluating Fold {fold_num}/{self.n_splits} on its Validation Set...")
            metrics = self.evaluate_epoch(model, val_loader, verbose=1)

            validate_perf_path = f"{fold_dir}/fold_{fold_num}_validate_perf_{weight_type}_weight.csv"
            pd.DataFrame([metrics]).to_csv(validate_perf_path, index=False)

            if self.first_metric in metrics:
                current_primary = metrics[self.first_metric]
                current_secondary = metrics.get(self.secondary_metric) if self.secondary_metric else None

                is_primary_better = (self.first_metric_mode == 'min' and current_primary < self.best_primary_val) or \
                                    (self.first_metric_mode == 'max' and current_primary > self.best_primary_val)

                is_primary_equal = (current_primary == self.best_primary_val)

                if is_primary_better:
                    self.best_primary_val = current_primary
                    if current_secondary is not None:
                        self.best_secondary_val = current_secondary
                    self.best_fold_num = fold_num

                elif is_primary_equal and self.secondary_metric and current_secondary is not None:
                    is_sec_better = (self.secondary_metric_mode == 'min' and current_secondary < self.best_secondary_val) or \
                                    (self.secondary_metric_mode == 'max' and current_secondary > self.best_secondary_val)
                    if is_sec_better:
                        self.best_secondary_val = current_secondary
                        self.best_fold_num = fold_num
            else:
                print(f"[Warning] Metric '{self.first_metric}' not found in evaluation metrics. Cannot determine best fold.")

            metrics_with_fold = {'Fold': f'Fold {fold_num}'}
            metrics_with_fold.update(metrics)
            all_fold_metrics.append(metrics_with_fold)

        df = pd.DataFrame(all_fold_metrics)
        numeric_df = df.drop('Fold', axis=1)

        mean_series = numeric_df.mean()
        std_series = numeric_df.std()

        mean_row = {'Fold': 'Mean'}
        mean_row.update(mean_series.to_dict())

        std_row = {'Fold': 'STD'}
        std_row.update(std_series.to_dict())

        summary_df = pd.DataFrame([mean_row, std_row])
        df_final = pd.concat([df, summary_df], ignore_index=True)

        print(f"\n{'-'*100}")
        print("K-Fold Validation Evaluation Results (Individual Models):")
        print(df_final.to_string(index=False))
        print(f"{'-'*100}")

        summary_validate_perf_path = f"{self.base_dir}/summary/kfold_validate_perf_{weight_type}_weight.csv"
        df_final.to_csv(summary_validate_perf_path, index=False)
        print(f"[Logs] Saved Overall Validation Summary to {summary_validate_perf_path}")

        if self.best_fold_num is not None:
            best_info = {
                'best_fold_num': self.best_fold_num,
                'weight_type': weight_type,
                'first_metric': self.first_metric,
                'first_metric_value': self.best_primary_val
            }

            if self.secondary_metric is not None:
                best_info['secondary_metric'] = self.secondary_metric
                best_info['secondary_metric_value'] = self.best_secondary_val

            info_path = f"{self.base_dir}/summary/best_fold_info.json"
            with open(info_path, 'w') as f:
                json.dump(best_info, f, indent=4)
            print(f"[Logs] Saved Best Fold Info to {info_path}")

        return df_final

    def predict_kfold(self,
                      dataloader: DataLoader,
                      model_fn: Callable[[], torch.nn.Module],
                      weight_type: str = 'best',
                      timer_report_dict: bool = False,
                      verbose: int = 1
                      ) -> Union[np.ndarray, Tuple[np.ndarray, Dict[str, float]]]:
        """
            The public method to predict using a model with k-fold cross validation.
            Args:
                - dataloader (DataLoader): Dataloader to use.
                - model_fn (Callable[[], torch.nn.Module]): Model
                - weight_type (str, optional): Weight type to use. Defaults to 'best' (Valid on 'best' or 'final').
                - timer_report_dict (bool, optional): Whether to report timer report. Defaults to False.
                - verbose (int, optional): Verbosity level (0 : None, 1 : Visible)
            Returns:
                - np.ndarray: Predictions (For used on classification report, correct_predict, incorrect_predict).
        """
        assert weight_type in ['best', 'final'], 'weight_type should be either best or final.'

        if verbose == 1:
            print(f"{'='*100}")
            print(f"Ensemble Prediction using {self.n_splits}-Fold Models ({weight_type.upper()} weights)")
            print(f"{'='*100}\n")

        all_folds_probs = []
        all_timing_reports = []

        for fold_num in range(1, self.n_splits + 1):
            fold_dir = f"{self.base_dir}/fold_{fold_num}"
            model = model_fn().to(self.device)

            weight_path = f"{fold_dir}/{self.model_name}_{self.dataset_name}_{weight_type}_weight.pth"
            load_model(save_path=weight_path, model=model, optimizer=None, device=self.device)

            if verbose == 1:
                print(f"[*] Running inference for Fold {fold_num}/{self.n_splits}...")

            pred_result = self.predict(model, dataloader, timer_report_dict=timer_report_dict, verbose=verbose)

            if timer_report_dict:
                probs, timing = pred_result
                all_timing_reports.append(timing)

                fold_timing_path = f"{fold_dir}/fold_{fold_num}_infer_timing_report.csv"
                pd.DataFrame([timing]).to_csv(fold_timing_path, index=False)
                if verbose == 1:
                    print(f"    -> Saved fold {fold_num} timing report to {fold_timing_path}")
            else:
                probs = pred_result

            all_folds_probs.append(probs)

            fold_pred_path = f"{fold_dir}/fold_{fold_num}_test_probs_{weight_type}_weight.csv"
            pd.DataFrame(probs).to_csv(fold_pred_path, index=False)
            if verbose == 1:
                print(f"    -> Saved fold {fold_num} predictions to {fold_pred_path}")

        # Ensemble Probabilities
        ensemble_probs = np.mean(all_folds_probs, axis=0)

        ensemble_dir = f"{self.base_dir}/ensemble"
        ensemble_pred_path = f"{ensemble_dir}/ensem_test_probs_{weight_type}_weight.csv"
        pd.DataFrame(ensemble_probs).to_csv(ensemble_pred_path, index=False)
        if verbose == 1:
            print(f"[Logs] Saved ensemble predictions to {ensemble_pred_path}")

        if timer_report_dict:
            if len(all_timing_reports) > 1:
                # Calc without first fold
                valid_reports = all_timing_reports[1:]
            else:
                valid_reports = all_timing_reports

            avg_latency_batch = np.mean([t['infer_latency'] for t in valid_reports])
            avg_latency_sample = np.mean([t['infer_latency_sample'] for t in valid_reports])
            avg_throughput = np.mean([t['infer_throughput'] for t in valid_reports])
            total_samples = all_timing_reports[0]['infer_total_samples']

            ensemble_timing_report = {
                'avg_single_model_latency_batch': avg_latency_batch,
                'avg_single_model_latency_sample': avg_latency_sample,
                'avg_single_model_throughput': avg_throughput,
                'ensemble_total_latency_sample': avg_latency_sample * self.n_splits,
                'infer_total_samples': total_samples
            }

            if verbose == 1:
                print(f"\n[Ensemble Inference Report]")
                print(f"Avg Single Model Latency Batch : {avg_latency_batch:.2f} ms/batch")
                print(f"Avg Single Model Latency Sample: {avg_latency_sample:.2f} ms/sample")
                print(f"Avg Single Model Throughput    : {avg_throughput:.2f} samples/s")
                print(f"Ensemble Total Latency Sample  : {ensemble_timing_report['ensemble_total_latency_sample']:.2f} ms/sample")
                print(f"{'='*100}")

            report_path = f"{ensemble_dir}/ensem_infer_timing_report.csv"
            pd.DataFrame([ensemble_timing_report]).to_csv(report_path, index=False)
            print(f"[Logs] Saved Inference Report to {report_path}")

            return ensemble_probs, ensemble_timing_report

        if verbose == 1:
            print(f"{'='*100}")

        return ensemble_probs

    def get_best_model_on_validate_set(self,
                       model_fn: Callable[[], torch.nn.Module],
                       ) -> Tuple[torch.nn.Module, str, int]:
        """
            The public method to get the best model on validation set.
            !!Need to run evaluate_kfold() first to generate best model info.!!
            Args:
                - model_fn (Callable[[], torch.nn.Module]): Model
            Returns:
                - Tuple[torch.nn.Module, str, int]: Best model on validation set, fold directory, best fold number.
        """
        info_path = f"{self.base_dir}/summary/best_fold_info.json"

        if not os.path.exists(info_path):
            raise FileNotFoundError(f"Cannot find '{info_path}'. Please run evaluate_kfold() first to generate best model info.")

        with open(info_path, 'r') as f:
            best_info = json.load(f)

        best_fold_num = best_info['best_fold_num']
        weight_type = best_info['weight_type']

        m1_name = best_info['first_metric']
        m1_val = best_info['first_metric_value']

        m2_str = ""
        if 'secondary_metric' in best_info:
            m2_name = best_info['secondary_metric']
            m2_val = best_info['secondary_metric_value']
            m2_str = f" | Secondary: {m2_name}->{m2_val:.4f}"

        print(f"[Logs] Retrieving Best Model from Fold {best_fold_num}")
        print(f"       Primary Metric: {m1_name}->{m1_val:.4f}{m2_str} on Validation set.")

        fold_dir = f"{self.base_dir}/fold_{best_fold_num}"
        model = model_fn().to(self.device)
        weight_path = f"{fold_dir}/{self.model_name}_{self.dataset_name}_{weight_type}_weight.pth"
        load_model(save_path=weight_path, model=model, optimizer=None, device=self.device)

        return model, fold_dir, best_fold_num