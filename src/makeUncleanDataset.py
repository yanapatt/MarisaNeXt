import os
import shutil
import pandas as pd

from . import buildDirectory

ISSUE_COLUMNS = {
    'candidateOutlier': 'Outlier',
    'intraDuplicate': 'Intra Duplicate',
    'interDuplicate': 'Inter Duplicate',
    'solidColor': 'Solid Color',
}

def _read_report(path):
    if path is None or not os.path.exists(path):
        return pd.DataFrame(columns=['filepaths', 'filename', 'label', 'issue'])
    try:
        return pd.read_csv(path)
    except pd.errors.EmptyDataError:
        return pd.DataFrame(columns=['filepaths', 'filename', 'label', 'issue'])

def _to_keys(df, label_col='label', filename_col='filename'):
    return set(zip(df[label_col].astype(str), df[filename_col].astype(str)))

def read_image_table(data_dir, extensions=('.jpg', '.jpeg', '.png')):
    filepaths, labels = buildDirectory.read_images(data_dir=data_dir, extensions=extensions)
    df = pd.DataFrame({
        'filepaths': filepaths,
        'filename': [os.path.basename(p) for p in filepaths],
        'label': labels,
    })
    if df.duplicated(['label', 'filename']).any():
        dup = df[df.duplicated(['label', 'filename'], keep=False)].head(4)['filepaths'].tolist()
        raise ValueError(f"[Error] Duplicated (label, filename) found under {data_dir}. e.g. {dup}")
    return df

def build_unclean_split(raw_dir, split_dir, output_dir, verify_csv, to_delete_csv,
                        intra_dup_csv=None, inter_dup_csv=None, exclude_issues=('corrupted',), report_dir=None,
                        data_name='dataset'):
    """
        This function builds the unclean split directory (remain = uncleaned, test = unchanged).

        Args:
            - Same as build_partial_clean_split (remove_issues = (), nothing is removed except exclude_issues)
        Returns:
            - summary_df (pd.DataFrame): Per-class counts of clean vs unclean remain
            - added_df (pd.DataFrame): Images added back to remain (with issue and test-leakage flag)

        Output directory tree
        - output_dir
            |- remain/{label}/{filename}   (uncleaned)
            |- test/{label}/{filename}     (copied from split_dir/test)
        - report_dir
            |- {data_name}_UNCLEAN_SUMMARY.csv
            |- {data_name}_UNCLEAN_ADDED.csv
    """
    return build_partial_clean_split(
        raw_dir=raw_dir,
        split_dir=split_dir,
        output_dir=output_dir,
        verify_csv=verify_csv,
        to_delete_csv=to_delete_csv,
        remove_issues=(),
        variant='UNCLEAN',
        variant_label='Unclean',
        intra_dup_csv=intra_dup_csv,
        inter_dup_csv=inter_dup_csv,
        exclude_issues=exclude_issues,
        report_dir=report_dir,
        data_name=data_name
    )

def build_partial_clean_split(raw_dir, split_dir, output_dir, verify_csv, to_delete_csv, remove_issues,
                              variant, variant_label, intra_dup_csv=None, inter_dup_csv=None,
                              exclude_issues=('corrupted',), report_dir=None, data_name='dataset'):
    """
        This function builds a partially cleaned split directory (remain = partially cleaned, test = unchanged).

            remain = RAW - exclude_issues (from verify_csv) - test - images in to_delete_csv with an issue in remove_issues

        An image listed with several issues in to_delete_csv is removed if ANY of its issues is in remove_issues.

        e.g.
            - KEEP_DUP     : remove_issues = ('candidateOutlier', 'solidColor')   -> duplicates are kept
            - KEEP_OUTLIER : remove_issues = ('intraDuplicate', 'interDuplicate') -> outliers / solid color are kept

        Args:
            - raw_dir (str): Directory of the extracted {data_name}_RAW.zip
            - split_dir (str): Directory of the extracted {data_name}_SPLIT.zip (contains remain/ and test/)
            - output_dir (str): Output directory (remain/ and test/ will be created here). Must not exist or be empty
            - verify_csv (str): Path of {data_name}_VERIFY.csv (Used to exclude truly corrupted images)
            - to_delete_csv (str): Path of {data_name}_TO_DELETE.csv (Used to remove / label the issue of the images)
            - remove_issues (tuple): Issues in to_delete_csv to remove from remain (e.g. ('candidateOutlier', 'solidColor'))
            - variant (str): Variant name used in the report filenames (e.g. 'KEEP_DUP')
            - variant_label (str): Variant label used in the summary column 'Remain {variant_label}' (e.g. 'Keep Dup')
            - intra_dup_csv (str): Path of {data_name}_INTRA_DUPLICATES.csv (Optional, used to flag test leakage)
            - inter_dup_csv (str): Path of {data_name}_INTER_DUPLICATES.csv (Optional, used to flag test leakage)
            - exclude_issues (tuple): Issues in verify_csv to exclude from remain (Default is ('corrupted',))
            - report_dir (str): Directory to save the reports (Optional)
            - data_name (str): Dataset name used in the report filenames
        Returns:
            - summary_df (pd.DataFrame): Per-class counts of clean vs variant remain
            - added_df (pd.DataFrame): Images added back to remain compared to the clean split (with issue and test-leakage flag)

        Output directory tree
        - output_dir
            |- remain/{label}/{filename}   (partially cleaned)
            |- test/{label}/{filename}     (copied from split_dir/test)
        - report_dir
            |- {data_name}_{variant}_SUMMARY.csv
            |- {data_name}_{variant}_ADDED.csv
    """
    if os.path.exists(output_dir) and os.listdir(output_dir):
        raise FileExistsError(f"[Error] Output directory is not empty: {output_dir}")

    split_remain_dir = os.path.join(split_dir, 'remain')
    split_test_dir = os.path.join(split_dir, 'test')
    for path in [raw_dir, split_remain_dir, split_test_dir]:
        if not os.path.isdir(path):
            raise FileNotFoundError(f"[Error] Directory not found: {path}")

    raw_df = read_image_table(raw_dir)
    clean_remain_df = read_image_table(split_remain_dir)
    test_df = read_image_table(split_test_dir)
    print(f"[*] RAW: {len(raw_df)} | Clean remain: {len(clean_remain_df)} | Test: {len(test_df)}")

    raw_keys = _to_keys(raw_df)
    test_keys = _to_keys(test_df)
    clean_keys = _to_keys(clean_remain_df) | test_keys

    # Every image of the existing split must come from RAW
    missing = clean_keys - raw_keys
    if missing:
        raise ValueError(f"[Error] {len(missing)} images in the existing split are not found in RAW. e.g. {sorted(missing)[:3]}")

    # Exclude only truly corrupted images (cannot be opened)
    verify_df = _read_report(verify_csv)
    excluded_df = verify_df[verify_df['issue'].isin(exclude_issues)] if len(verify_df) else verify_df
    excluded_keys = _to_keys(excluded_df) if len(excluded_df) else set()
    if excluded_keys & test_keys:
        raise ValueError("[Error] Excluded (corrupted) images are found in the test set.")
    print(f"[*] Excluded {len(excluded_keys & raw_keys)} image(s) with issue {list(exclude_issues)}")

    # Images listed in to_delete_csv with an issue in remove_issues
    to_delete_df = _read_report(to_delete_csv)
    issue_map = {}
    for label, filename, issue in zip(to_delete_df['label'].astype(str), to_delete_df['filename'].astype(str), to_delete_df['issue'].astype(str)):
        issue_map.setdefault((label, filename), []).append(issue)
    removed_keys = {k for k, issues in issue_map.items() if set(issues) & set(remove_issues)} - excluded_keys
    if removed_keys & test_keys:
        raise ValueError("[Error] Images to remove are found in the test set.")
    if remove_issues:
        print(f"[*] Removed {len(removed_keys & raw_keys)} image(s) with issue {list(remove_issues)}")

    # remain = RAW - excluded - test - removed
    drop_keys = test_keys | excluded_keys | removed_keys
    remain_df = raw_df[[k not in drop_keys for k in zip(raw_df['label'], raw_df['filename'])]]
    remain_df = remain_df.reset_index(drop=True)
    remain_keys = _to_keys(remain_df)

    if not _to_keys(clean_remain_df) <= remain_keys:
        raise ValueError(f"[Error] Clean remain is not a subset of {variant_label.lower()} remain.")

    # Images added back compared to the clean split (removed during cleaning)
    added_keys = remain_keys - _to_keys(clean_remain_df)
    added_df = remain_df[[k in added_keys for k in zip(remain_df['label'], remain_df['filename'])]].copy()
    # dtype is set explicitly so that an empty added_df (nothing added back) still has string / bool columns
    added_df['issue'] = pd.Series(['|'.join(issue_map.get(k, ['unknown'])) for k in zip(added_df['label'], added_df['filename'])],
                                  index=added_df.index, dtype=object)

    n_unknown = int((added_df['issue'] == 'unknown').sum())
    if n_unknown:
        print(f"[Warning] {n_unknown} added image(s) are not listed in {os.path.basename(str(to_delete_csv))} (issue = 'unknown').")

    # Flag duplicates whose hash group has a member in the test set (test leakage, kept on purpose)
    test_hash_groups = set()
    group_of = {}
    for dup_csv in [intra_dup_csv, inter_dup_csv]:
        dup_df = _read_report(dup_csv)
        if len(dup_df) and 'hash_group' in dup_df.columns:
            for label, filename, group in zip(dup_df['label'].astype(str), dup_df['filename'].astype(str), dup_df['hash_group'].astype(str)):
                group_of.setdefault((label, filename), set()).add(group)
                if (label, filename) in test_keys:
                    test_hash_groups.add(group)
    added_df['duplicate_of_test'] = pd.Series([bool(group_of.get(k, set()) & test_hash_groups) for k in zip(added_df['label'], added_df['filename'])],
                                              index=added_df.index, dtype=bool)
    added_df = added_df.sort_values(['label', 'filename']).reset_index(drop=True)

    # Build output directory
    out_remain_dir = os.path.join(output_dir, 'remain')
    out_test_dir = os.path.join(output_dir, 'test')
    buildDirectory.to_directory(remain_df['filepaths'], remain_df['label'], out_remain_dir)
    shutil.copytree(split_test_dir, out_test_dir)

    # Verify output
    out_remain_keys = _to_keys(read_image_table(out_remain_dir))
    out_test_keys = _to_keys(read_image_table(out_test_dir))
    if out_remain_keys != remain_keys or out_test_keys != test_keys or (out_remain_keys & out_test_keys):
        raise RuntimeError("[Error] Output verification failed.")
    print(f"[*] Output verified: remain = {len(out_remain_keys)} | test = {len(out_test_keys)} (identical to the existing split) | overlap = 0")

    # Summary per class
    labels = sorted(set(raw_df['label']))
    summary_rows = []
    for label in labels:
        added_label = added_df[added_df['label'] == label]
        row = {
            'Labels': label,
            'Remain Clean': int((clean_remain_df['label'] == label).sum()),
            f'Remain {variant_label}': int((remain_df['label'] == label).sum()),
            'Added': len(added_label),
        }
        for issue, col in ISSUE_COLUMNS.items():
            row[col] = int(added_label['issue'].astype(str).str.contains(issue, regex=False).sum())
        row['Duplicate of Test'] = int(added_label['duplicate_of_test'].sum())
        row['Test'] = int((test_df['label'] == label).sum())
        summary_rows.append(row)

    summary_df = pd.DataFrame(summary_rows)
    total_row = {'Labels': 'Total'}
    total_row.update(summary_df.drop(columns='Labels').sum().to_dict())
    summary_df = pd.concat([summary_df, pd.DataFrame([total_row])], ignore_index=True)

    if report_dir:
        os.makedirs(report_dir, exist_ok=True)
        summary_path = os.path.join(report_dir, f"{data_name}_{variant}_SUMMARY.csv")
        added_path = os.path.join(report_dir, f"{data_name}_{variant}_ADDED.csv")
        summary_df.to_csv(summary_path, index=False)
        added_df.to_csv(added_path, index=False)
        print(f"[Logs] Saved Summary to: {summary_path}")
        print(f"[Logs] Saved Added Images to: {added_path}")

    print(f"\n{'-'*100}")
    print(f"{variant_label} split summary ({data_name})")
    print(summary_df.to_string(index=False))
    print(f"{'-'*100}")

    return summary_df, added_df