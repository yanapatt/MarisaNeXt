import os
import time
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.metrics import accuracy_score, f1_score, precision_score, recall_score
from sklearn.metrics import classification_report, confusion_matrix

from . import test as test_utils
from . import visualization

VOTING_METHODS = ['soft', 'hard', 'weighted']

def _to_labels(y_probs):
    if y_probs.ndim == 2 and y_probs.shape[1] > 1:
        return np.argmax(y_probs, axis=1)
    return (y_probs >= 0.5).astype(int).reshape(-1)

def _to_two_columns(y_probs):
    if y_probs.ndim == 2 and y_probs.shape[1] > 1:
        return y_probs
    p = y_probs.reshape(-1)
    return np.stack([1.0 - p, p], axis=1)

def _read_csv_or_empty(path):
    try:
        return pd.read_csv(path)
    except pd.errors.EmptyDataError:
        return pd.DataFrame()

def load_fold_probs(base_dir, n_splits, weight_type='best'):
    assert weight_type in ['best', 'final'], "weight_type must be 'best' or 'final'"

    all_probs = []
    for fold_num in range(1, n_splits + 1):
        prob_path = os.path.join(base_dir, f"fold_{fold_num}", f"fold_{fold_num}_test_probs_{weight_type}_weight.csv")
        if not os.path.exists(prob_path):
            raise FileNotFoundError(f"[Error] Probabilities file not found: {prob_path}")
        y_probs = pd.read_csv(prob_path).values
        print(f"[*] Loaded Fold {fold_num}/{n_splits} probabilities | Shape: {y_probs.shape}")
        all_probs.append(y_probs)

    return np.stack(all_probs, axis=0)

def load_fold_val_accuracy(base_dir, n_splits, weight_type='best'):
    val_acc = []
    for fold_num in range(1, n_splits + 1):
        perf_path = os.path.join(base_dir, f"fold_{fold_num}", f"fold_{fold_num}_validate_perf_{weight_type}_weight.csv")
        if not os.path.exists(perf_path):
            raise FileNotFoundError(f"[Error] Validation performance file not found: {perf_path}")
        val_acc.append(float(pd.read_csv(perf_path)['accuracy'].iloc[0]))

    return np.array(val_acc)

def load_test_records(base_dir, weight_type='best', prefix='ensem'):
    ensem_dir = os.path.join(base_dir, 'ensemble')
    correct_path = os.path.join(ensem_dir, f"{prefix}_correct_preds.csv")
    incorrect_path = os.path.join(ensem_dir, f"{prefix}_incorrect_preds.csv")
    for path in [correct_path, incorrect_path]:
        if not os.path.exists(path):
            raise FileNotFoundError(f"[Error] Prediction records not found: {path}")

    df = pd.concat([_read_csv_or_empty(correct_path), _read_csv_or_empty(incorrect_path)], ignore_index=True)
    df['_dir'] = df['Filepaths'].map(os.path.dirname)
    df['_file'] = df['Filepaths'].map(os.path.basename)
    df = df.sort_values(['True_Index', '_dir', '_file'], kind='mergesort').reset_index(drop=True)

    ensem_probs_path = os.path.join(ensem_dir, f"{prefix}_test_probs_{weight_type}_weight.csv")
    if os.path.exists(ensem_probs_path):
        saved_pred = _to_labels(pd.read_csv(ensem_probs_path).values)
        if len(saved_pred) != len(df) or not np.array_equal(saved_pred, df['Pred_Index'].values):
            raise ValueError("[Error] Recovered test order does not match the saved ensemble probabilities. "
                             "Please pass y_true from test.get_true_label(test_loader) instead.")
        print(f"[*] Recovered test order verified against {ensem_probs_path}")
    else:
        print(f"[Warning] {ensem_probs_path} not found. Recovered test order cannot be verified.")

    idx_to_class = dict(sorted({int(i): c for i, c in zip(df['True_Index'], df['True_Label'])}.items()))
    idx_to_class.update({int(i): c for i, c in zip(df['Pred_Index'], df['Pred_Label']) if int(i) not in idx_to_class})
    idx_to_class = dict(sorted(idx_to_class.items()))

    y_true = df['True_Index'].values.astype(int)
    filepaths = df['Filepaths'].tolist()
    print(f"[*] Recovered {len(y_true)} test samples | {len(idx_to_class)} classes")

    return y_true, filepaths, idx_to_class

def soft_voting(fold_probs):
    """
        Soft voting: mean of fold probabilities.
        Args:
            - fold_probs (np.array): Probabilities with shape (K, N, C)
        Returns:
            - y_probs (np.array): Ensemble probabilities with shape (N, C)
    """
    return np.mean(fold_probs, axis=0)

def hard_voting(fold_probs):
    """
        Hard voting (max voting): l = mode(e_1, ..., e_K) where e_k is the predicted label of the k-th model.
        Ties are broken by the lowest class index.
        Args:
            - fold_probs (np.array): Probabilities with shape (K, N, C) (or (K, N) / (K, N, 1) for binary)
        Returns:
            - y_pred (np.array): Ensemble predicted labels with shape (N,)
            - vote_counts (np.array): Number of votes per class with shape (N, C)
    """
    fold_labels = np.stack([_to_labels(p) for p in fold_probs], axis=0)  # (K, N)
    n_classes = _to_two_columns(fold_probs[0]).shape[1]

    vote_counts = np.stack([(fold_labels == c).sum(axis=0) for c in range(n_classes)], axis=1)  # (N, C)
    # np.argmax returns the first max -> lowest class index wins on ties
    y_pred = np.argmax(vote_counts, axis=1)

    return y_pred, vote_counts

def weighted_voting(fold_probs, weights):
    """
        Weighted soft voting: sum_k w_k * P_k with sum_k w_k = 1.
        Args:
            - fold_probs (np.array): Probabilities with shape (K, N, C)
            - weights (np.array): Weight of each model with shape (K,)
        Returns:
            - y_probs (np.array): Ensemble probabilities with shape (N, C)
    """
    weights = np.asarray(weights, dtype=float)
    weights = weights / weights.sum()
    return np.tensordot(weights, fold_probs, axes=1)

def evaluate_labels(y_true, y_pred, task='multiclass', average='macro'):
    calc_average = 'binary' if task == 'binary' else average
    return {
        'loss': None,
        'accuracy': accuracy_score(y_true, y_pred),
        'f1': f1_score(y_true, y_pred, average=calc_average, zero_division=0),
        'precision': precision_score(y_true, y_pred, average=calc_average, zero_division=0),
        'recall': recall_score(y_true, y_pred, average=calc_average, zero_division=0),
    }

def _aggregation_time_ms(fn, n_samples, repeats=10):
    result = fn()
    start = time.perf_counter()
    for _ in range(repeats):
        fn()
    elapsed = (time.perf_counter() - start) / repeats
    return result, elapsed * 1000.0 / max(n_samples, 1)

def compare_voting_strategies(base_dir, n_splits, weight_type='best', task='multiclass', average='macro',
                              y_true=None, filepaths=None, idx_to_class=None, title=None,
                              cmap=plt.cm.YlGnBu, cm_figsize=(12, 8), roc_figsize=(14, 6), fontsize=14,
                              plot=True):
    """
        This function compares soft, hard and weighted voting from the saved fold probabilities.

        Args:
            - base_dir (str): Base directory of the experiment
            - n_splits (int): Number of splits
            - weight_type (str): Type of weight (Include 'best' and 'final') Default is 'best'
            - task (str): Type of task (Include 'multiclass' and 'binary') Default is 'multiclass'
            - average (str): Type of average (Include 'macro', 'micro', 'weighted') Default is 'macro'
            - y_true (np.array): True labels (Optional). If None, recovered from the saved ensemble records
            - filepaths (list): List of filepaths (Optional). If None, recovered from the saved ensemble records
            - idx_to_class (dict): Dictionary of index to class (Optional). If None, recovered from the saved ensemble records
            - title (str): Title prefix of the figures (Optional) e.g. 'ConvNeXt-Tiny Ensemble on MushroomA Dataset'
            - cmap (matplotlib.colors.Colormap): Colormap of the confusion matrix
            - cm_figsize (tuple): Figure size of the confusion matrix
            - roc_figsize (tuple): Figure size of the ROC-AUC curve
            - fontsize (int): Font size of the figures
            - plot (bool): Whether to plot and save the confusion matrix / ROC-AUC curve (Default is True)
        Returns:
            - comparison_df (pd.DataFrame): Metrics and latency of each voting method
            - results (dict): Per-method outputs {'y_pred', 'y_probs', 'metrics', 'report_df', 'df_correct', 'df_incorrect'}

        Output directory tree
        - base_dir
            |- ensemble_addition
                |- voting_comparison_{weight_type}_weight.csv
                |- voting_weights_{weight_type}_weight.csv
                |- soft / hard / weighted
                    |- {method}_test_probs_{weight_type}_weight.csv   (hard: {method}_test_votes_{weight_type}_weight.csv)
                    |- {method}_test_perf_{weight_type}_weight.csv
                    |- {method}_classification_report.csv
                    |- {method}_correct_preds.csv / {method}_incorrect_preds.csv
                    |- conf_matrix_unnorm / conf_matrix_norm (.png, .svg)
                    |- roc_auc_curve (.png, .svg)   (soft / weighted only)
    """
    assert weight_type in ['best', 'final'], "weight_type must be 'best' or 'final'"
    assert task in ['multiclass', 'binary'], "task must be 'multiclass' or 'binary'"
    assert average in ['macro', 'micro', 'weighted'], "average must be 'macro', 'micro', or 'weighted'"

    # Inputs
    fold_probs = load_fold_probs(base_dir, n_splits, weight_type)
    n_samples = fold_probs.shape[1]

    if y_true is None or filepaths is None or idx_to_class is None:
        rec_y_true, rec_filepaths, rec_idx_to_class = load_test_records(base_dir, weight_type)
        y_true = rec_y_true if y_true is None else np.asarray(y_true)
        filepaths = rec_filepaths if filepaths is None else filepaths
        idx_to_class = rec_idx_to_class if idx_to_class is None else idx_to_class

    if len(y_true) != n_samples:
        raise ValueError(f"[Error] y_true has {len(y_true)} samples but fold probabilities have {n_samples} samples.")

    class_names = [idx_to_class[i] for i in sorted(idx_to_class)]

    val_acc = load_fold_val_accuracy(base_dir, n_splits, weight_type)
    weights = val_acc / val_acc.sum()

    voting_dir = os.path.join(base_dir, 'ensemble_addition')
    os.makedirs(voting_dir, exist_ok=True)

    weights_df = pd.DataFrame({
        'Fold': [f'Fold {k}' for k in range(1, n_splits + 1)],
        'val_accuracy': val_acc,
        'weight': weights
    })
    weights_path = os.path.join(voting_dir, f"voting_weights_{weight_type}_weight.csv")
    weights_df.to_csv(weights_path, index=False)
    print(f"[Logs] Saved Voting Weights to: {weights_path}")

    # Inference latency of a single model (Saved by KFoldTrainer.predict_kfold)
    timing_path = os.path.join(base_dir, 'ensemble', f"ensem_infer_timing_report.csv")
    single_latency = None
    if os.path.exists(timing_path):
        single_latency = float(pd.read_csv(timing_path)['avg_single_model_latency_sample'].iloc[0])

    voting_fns = {
        'soft': lambda: soft_voting(fold_probs),
        'hard': lambda: hard_voting(fold_probs),
        'weighted': lambda: weighted_voting(fold_probs, weights),
    }

    results = {}
    comparison_rows = []

    for method in VOTING_METHODS:
        print(f"\n{'='*100}")
        print(f"Voting Method: {method.upper()}")
        print(f"{'='*100}")

        method_dir = os.path.join(voting_dir, method)
        os.makedirs(method_dir, exist_ok=True)
        perf_path = os.path.join(method_dir, f"{method}_test_perf_{weight_type}_weight.csv")

        output, agg_ms = _aggregation_time_ms(voting_fns[method], n_samples)

        if method == 'hard':
            y_pred, vote_counts = output
            # Vote fraction is used only as the 'Prob' column of the prediction records
            y_probs = vote_counts / float(n_splits)
            metrics = evaluate_labels(y_true, y_pred, task=task, average=average)
            pd.DataFrame([metrics]).to_csv(perf_path, index=False)
            print(f"[Logs] Saved Metrics to: {perf_path}")

            votes_path = os.path.join(method_dir, f"{method}_test_votes_{weight_type}_weight.csv")
            pd.DataFrame(vote_counts).to_csv(votes_path, index=False)
        else:
            y_probs = output
            y_pred, metrics = test_utils.evaluate_preds(
                y_true=y_true,
                y_probs=y_probs,
                task=task,
                average=average,
                save_path=perf_path
            )
            probs_path = os.path.join(method_dir, f"{method}_test_probs_{weight_type}_weight.csv")
            pd.DataFrame(y_probs).to_csv(probs_path, index=False)

        # Classification report
        report_dict = classification_report(y_true, y_pred, digits=4, target_names=class_names,
                                            labels=list(range(len(class_names))), output_dict=True, zero_division=0)
        report_df = pd.DataFrame(report_dict).transpose()
        report_df.to_csv(os.path.join(method_dir, f"{method}_classification_report.csv"))
        print(classification_report(y_true, y_pred, digits=4, target_names=class_names,
                                    labels=list(range(len(class_names))), zero_division=0))

        # Correct / incorrect predictions
        df_correct, df_incorrect = test_utils.pred_records(
            y_true=y_true,
            y_pred=y_pred,
            y_probs=y_probs,
            filepaths=filepaths,
            idx_to_class=idx_to_class,
            save_dir=method_dir,
            prefix=method
        )

        # Figures
        if plot:
            fig_title = f"{title} ({method.capitalize()} Voting)" if title else f"{method.capitalize()} Voting"
            cm = confusion_matrix(y_true, y_pred, labels=list(range(len(class_names))))
            for norm in [False, True]:
                visualization.plot_confusion_matrix(
                    cm=cm,
                    class_names=class_names,
                    norm=norm,
                    cmap=cmap,
                    task=task,
                    figsize=cm_figsize,
                    fontsize=fontsize,
                    title=fig_title,
                    save_path=method_dir
                )
                print('\n')

            if method != 'hard':
                visualization.plot_roc_auc_curve(
                    y_true=y_true,
                    y_pred_probs=y_probs,
                    class_names=class_names,
                    task=task,
                    legend_ncol=1,
                    figsize=roc_figsize,
                    fontsize=fontsize,
                    title=fig_title,
                    save_path=method_dir
                )
                print('\n')

        row = {'Method': f'{method.capitalize()} Voting'}
        row.update(metrics)
        row['n_models'] = n_splits
        row['Aggregation Latency (ms/img)'] = agg_ms
        if single_latency is not None:
            row['Inference Latency (ms/img)'] = single_latency * n_splits
            row['Total Latency (ms/img)'] = single_latency * n_splits + agg_ms
        comparison_rows.append(row)

        results[method] = {
            'y_pred': y_pred,
            'y_probs': y_probs,
            'metrics': metrics,
            'report_df': report_df,
            'df_correct': df_correct,
            'df_incorrect': df_incorrect,
        }

    comparison_df = pd.DataFrame(comparison_rows)
    comparison_path = os.path.join(voting_dir, f"voting_comparison_{weight_type}_weight.csv")
    comparison_df.to_csv(comparison_path, index=False)

    print(f"\n{'-'*100}")
    print(f"Ensemble Voting Comparison on Test Set ({n_splits} models):")
    print(comparison_df.to_string(index=False))
    print(f"{'-'*100}")
    print(f"[Logs] Saved Voting Comparison to: {comparison_path}")

    return comparison_df, results