# สำหรับคำนวณ Metrics ต่าง ๆ
def perf_metrics(y_pred, y_true, n_classes, task='multiclass', average='macro'):
    if task == 'multiclass' and y_true.ndim > 1 and y_true.size(1) > 1:
        y_true = torch.argmax(y_true, dim=1)

    if task == 'binary':
        if y_pred.ndim == 2 and y_pred.size(1) == 1:
            y_pred = y_pred.squeeze(dim=1)
        if y_true.ndim == 2 and y_true.size(1) == 1:
            y_true = y_true.squeeze(dim=1)

        y_true = y_true.long()

    acc = accuracy(y_pred, y_true, task=task, num_classes=n_classes) # ไม่ต้องใช้ average
    f1 = f1_score(y_pred, y_true, task=task, num_classes=n_classes, average=average)
    prec = precision(y_pred, y_true, task=task, num_classes=n_classes, average=average)
    rec = recall(y_pred, y_true, task=task, num_classes=n_classes, average=average)

    return float(acc), float(f1), float(prec), float(rec)

# Training loop
def train(
        model, optimizer, epoch, total_epochs, device, dataloader,
        criterion, n_classes, task='multiclass', average='macro', max_grad_norm=0.0
        ):

    total_batches = len(dataloader)
    model.train()

    running_loss = 0.0
    total_samples = 0

    all_preds = []
    all_labels = []

    running_time_ms = 0.0
    use_cuda = device.type == 'cuda'
    if use_cuda:
        # Reference: https://docs.pytorch.org/docs/stable/notes/cuda.html => (Asynchronous execution)
        start_event = torch.cuda.Event(enable_timing=True)
        end_event = torch.cuda.Event(enable_timing=True)

    kbar = Kbar(target=total_batches, epoch=epoch, num_epochs=total_epochs,
                width=30, always_stateful=True)

    for i, (inputs, labels) in enumerate(dataloader):
        if use_cuda:
            start_event.record()
        else:
            iter_start = time()

        inputs = inputs.to(device, non_blocking=True)
        labels = labels.to(device, non_blocking=True)

        if task == 'multiclass':
            labels = labels.long()
            if labels.ndim == 2:
                labels = labels.squeeze(1)
        else:
            # binary
            labels = labels.float()
            if labels.ndim == 1:
                labels = labels.unsqueeze(1)

        optimizer.zero_grad()
        outputs = model(inputs)

        loss = criterion(outputs, labels)
        loss.backward()

        if max_grad_norm > 0:
            clip_grad_norm_(model.parameters(), max_grad_norm)
        optimizer.step()

        if use_cuda:
            end_event.record()
            torch.cuda.synchronize()
            iter_ms = start_event.elapsed_time(end_event) # ได้หน่วย ms อยู่แล้ว
        else:
            iter_end = time()
            iter_ms = (iter_end - iter_start) * 1000 # แปลงให้จาก s => ms

        running_time_ms += iter_ms

        batch_size = inputs.size(0)
        running_loss += loss.item() * batch_size
        total_samples += batch_size

        # คำนวณ metrics ต่อ batch เพื่อแสดง logs
        if task == 'multiclass':
            b_preds = torch.argmax(outputs, dim=1)
        else:
            # task == 'binary'
            probs = torch.sigmoid(outputs)
            b_preds = (probs > 0.5).float()

            if b_preds.ndim > 1: b_preds = b_preds.view(-1)
            if labels.ndim > 1: labels = labels.view(-1)

        b_acc, b_f1, b_prec, b_rec = perf_metrics(
            b_preds, labels, n_classes, task, average)

        all_preds.append(b_preds.detach().cpu())
        all_labels.append(labels.detach().cpu())

        b_lr = optimizer.param_groups[0]['lr']

        kbar.update(i, values=[
            ('loss', loss.item()),
            ('accuracy', b_acc),
            ('f1', b_f1),
            ('precision', b_prec),
            ('recall', b_rec),
            ('lr', b_lr)
        ])

    # ป้องกันการหารด้วย 0
    if total_samples == 0:
        return {key: 0.0 for key in ['loss', 'accuracy', 'f1', 'precision', 'recall', 'lr']}

    # คำนวณ metrics ระดับ epoch เพื่อแสดง logs สุดท้าย
    e_preds = torch.cat(all_preds)
    e_labels = torch.cat(all_labels)

    e_loss = running_loss / total_samples
    e_acc, e_f1, e_prec, e_rec = perf_metrics(
        e_preds, e_labels, n_classes, task, average)

    e_lr = optimizer.param_groups[0]['lr']

    # 1. Latency (ms/batch)
    e_latency = running_time_ms / total_batches

    # 2. Throughput (samples/s)
    total_seconds = running_time_ms / 1000
    e_throughput = total_samples / total_seconds

    kbar.add(1, values=[
        ('loss', e_loss),
        ('accuracy', e_acc),
        ('f1', e_f1),
        ('precision', e_prec),
        ('recall', e_rec),
        ('lr', e_lr),
        ('latency', e_latency),
        ('throughput', e_throughput)
    ])

    return {
        'loss': e_loss,
        'accuracy': e_acc,
        'f1': e_f1,
        'precision': e_prec,
        'recall': e_rec,
        'lr': e_lr,
        'latency': e_latency,
        'throughput': e_throughput
    }

# Evaluation
def evaluate(
        model, device, dataloader, criterion,
        n_classes, task='multiclass', average='macro', verbose=True
        ):

    total_batches = len(dataloader)
    model.eval()

    running_loss = 0.0
    total_samples = 0

    all_preds = []
    all_labels = []

    kbar = None
    if verbose:
        kbar = Kbar(target=total_batches, width=30, always_stateful=True)

    with torch.inference_mode():
        for i, (inputs, labels) in enumerate(dataloader):
            inputs = inputs.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)

            if task == 'multiclass':
                labels = labels.long()
                if labels.ndim == 2:
                    labels = labels.squeeze(1)
            else:
                # binary
                labels = labels.float()
                if labels.ndim == 1:
                    labels = labels.unsqueeze(1)

            outputs = model(inputs)
            loss = criterion(outputs, labels)

            batch_size = inputs.size(0)
            running_loss += loss.item() * batch_size
            total_samples += batch_size

            # คำนวณ metrics ต่อ batch เพื่อแสดง logs
            if task == 'multiclass':
                b_preds = torch.argmax(outputs, dim=1)
            else:
                # task == 'binary'
                probs = torch.sigmoid(outputs)
                b_preds = (probs > 0.5).float()

                if b_preds.ndim > 1: b_preds = b_preds.view(-1)
                if labels.ndim > 1: labels = labels.view(-1)

            all_preds.append(b_preds.detach().cpu())
            all_labels.append(labels.detach().cpu())

            if kbar:
                b_acc, b_f1, b_prec, b_rec = perf_metrics(
                    b_preds, labels, n_classes, task, average)

                kbar.update(i, values=[
                    ('loss', loss.item()),
                    ('accuracy', b_acc),
                    ('f1', b_f1),
                    ('precision', b_prec),
                    ('recall', b_rec)
                ])

    # ป้องกันการหารด้วย 0
    if total_samples == 0:
        return {key: 0.0 for key in ['loss', 'accuracy', 'f1', 'precision', 'recall']}

    # คำนวณ metrics ระดับ epoch เพื่อแสดง logs สุดท้าย
    e_preds = torch.cat(all_preds)
    e_labels = torch.cat(all_labels)

    e_loss = running_loss / total_samples
    e_acc, e_f1, e_prec, e_rec = perf_metrics(
        e_preds, e_labels, n_classes, task, average)

    if kbar:
        kbar.add(1, values=[
            ('loss', e_loss),
            ('accuracy', e_acc),
            ('f1', e_f1),
            ('precision', e_prec),
            ('recall', e_rec)
        ])

    return {
        'loss': e_loss,
        'accuracy': e_acc,
        'f1': e_f1,
        'precision': e_prec,
        'recall': e_rec
    }

def fit(train_loader, val_loader, model, optimizer, epochs, device, criterion, n_classes,
        task='multiclass', average='macro', initial_epoch=0, resume_history=None, callbacks=None, scheduler=None, save_path=None
        ):

    if callbacks is None:
        callbacks = []
    elif not isinstance(callbacks, list):
        callbacks = [callbacks] # แปลงเป็น list ให้

    if resume_history:
        history = defaultdict(list, resume_history)
    else:
        history = defaultdict(list)

    start_time = time() # Global time

    for epoch in range(initial_epoch, epochs):
        train_metrics = train(model, optimizer, epoch, epochs, device, train_loader, criterion, n_classes, task, average)
        val_metrics = evaluate(model, device, val_loader, criterion, n_classes, task, average, verbose=False)

        logs = train_metrics.copy()
        for key, value in val_metrics.items():
            logs[f'val_{key}'] = value # ใส่ prefix 'val_' นำหน้า metrics string

        if scheduler:
            # เฉพาะ ReduceLROnPlateau ที่ monitor ค่า val_loss
            if isinstance(scheduler, torch.optim.lr_scheduler.ReduceLROnPlateau):
                scheduler.step(logs['val_loss'])
            else:
                scheduler.step()

        history['epoch'].append(epoch + 1)

        for key, value in logs.items():
            val = value.item() if hasattr(value, 'item') else value
            history[key].append(val)

        print(f"val_loss: {logs['val_loss']:.4f} - val_accuracy: {logs['val_accuracy']:.4f} - val_f1: {logs['val_f1']:.4f} - val_precision: {logs['val_precision']:.4f} - val_recall: {logs['val_recall']:.4f}")

        # Early stopping callback
        stop_signal = False
        for callback in callbacks:
            callback.on_epoch_end(model, optimizer, epoch, logs)

            if getattr(callback, 'is_stop', False):
                stop_signal = True

        if stop_signal:
            break

    duration = time() - start_time
    print('-' * 150)
    print(f'[Logs] Training completed in {duration:.2f} seconds')

    # Model checkpoint callback
    for callback in callbacks:
        if callback.__class__.__name__ ==  'ModelCheckpoint':
            print(f'[Logs] Best model found at epoch {callback.best_epoch} ({callback.monitor}: {callback.best_score:.4f})')

    if save_path:
        save_model(
            save_path=save_path,
            model=model,
            optimizer=optimizer,
            epoch=epochs
        )
        print(f'[Logs] Model final weights has been saved to {save_path}')

    return history

# Prediction
def predict(dataloader, model, device, task='multiclass', report_dict=False):
    model.eval()
    all_probs = []

    running_time_ms = 0.0
    total_batches = len(dataloader)
    total_inference_samples = 0

    use_cuda = device.type == 'cuda'
    if use_cuda:
        start_event = torch.cuda.Event(enable_timing=True)
        end_event = torch.cuda.Event(enable_timing=True)

    kbar = Kbar(target=total_batches, width=30, always_stateful=True)

    with torch.inference_mode():
        for i, batch in enumerate(dataloader):
            # ดึงเฉพาะ inputs มา
            if isinstance(batch, (list, tuple)):
                inputs = batch[0]
            else:
                inputs = batch

            inputs = inputs.to(device, non_blocking=True)
            batch_size = inputs.size(0)
            total_inference_samples += batch_size

            if use_cuda:
                start_event.record()
            else:
                iter_start = time()

            outputs = model(inputs)

            if use_cuda:
                end_event.record()
                torch.cuda.synchronize()
                iter_ms = start_event.elapsed_time(end_event)
            else:
                iter_end = time()
                iter_ms = (iter_end - iter_start) * 1000

            running_time_ms += iter_ms

            if task == 'multiclass':
                probs = torch.softmax(outputs, dim=1)
            else:
                # task == 'binary'
                probs = torch.sigmoid(outputs)
                if probs.ndim > 1: probs = probs.view(-1)

            all_probs.append(probs.detach().cpu())
            kbar.add(1)

    out_probs = torch.cat(all_probs).numpy()

    if report_dict:
        # 1. Latency (ms/batch)
        latency_batch = running_time_ms / total_batches

        # 2. Latency (ms/sample)
        latency_sample = running_time_ms / total_inference_samples

        # 3. Throughput (samples/s)
        total_seconds = running_time_ms / 1000
        throughput = total_inference_samples / total_seconds

        report = {
            'infer_latency': latency_batch,
            'infer_latency_sample': latency_sample,
            'infer_throughput': throughput,
            'infer_total_samples': total_inference_samples
        }
        return out_probs, report

    return out_probs