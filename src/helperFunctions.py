# ตั้งค่า Font display
def matplotlib_font(font_dir, prefer_name=None):
    font_dir = pathlib.Path(font_dir)

    if not font_dir.exists():
        raise FileNotFoundError(f'Font directory not found: {font_dir}')

    font_files = font_manager.findSystemFonts(fontpaths=[str(font_dir)])

    if not font_files:
        raise RuntimeError(f'No font files found in {font_dir}')

    for font in font_files:
        font_manager.fontManager.addfont(font)

    selected_font = None
    for font in font_files:
        name = font_manager.FontProperties(fname=font).get_name()

        if prefer_name and prefer_name.lower() in name.lower():
            selected_font = name
            break

        if selected_font is None:
            selected_font = name

    matplotlib.rcParams['font.family'] = selected_font
    return selected_font

# Plot learning curve
def plot_lr_curve(history, figsize=(12, 5), fontsize=16, title=None, save_path=None):
    epochs = range(1, len(history['accuracy']) + 1)
    fig = plt.figure(figsize=figsize)

    # Loss
    plt.subplot(1, 2, 1)
    plt.plot(epochs, history['loss'], 'b-', label='Training loss')
    plt.plot(epochs, history['val_loss'], 'r-', label='Validation loss')
    plt.title('Training and validation loss', fontsize=fontsize)
    plt.xlabel('Epochs', fontsize=fontsize)
    plt.ylabel('Loss', fontsize=fontsize)
    plt.legend(fontsize=fontsize-2)
    plt.xticks(fontsize=fontsize-2)
    plt.yticks(fontsize=fontsize-2)

    # Accuracy
    plt.subplot(1, 2, 2)
    plt.plot(epochs, history['accuracy'], 'b-', label='Training accuracy')
    plt.plot(epochs, history['val_accuracy'], 'r-', label='Validation accuracy')
    plt.title('Training and validation accuracy', fontsize=fontsize)
    plt.xlabel('Epochs', fontsize=fontsize)
    plt.ylabel('Accuracy', fontsize=fontsize)
    plt.legend(fontsize=fontsize-2)
    plt.xticks(fontsize=fontsize-2)
    plt.yticks(fontsize=fontsize-2)

    plt.tight_layout()

    if title:
        fig.text(0.5, 0.01, f'{title}', ha='center', fontsize=fontsize)

    if save_path:
        plt.savefig(f'{save_path}/lr_curve.png', format='png', dpi=300, bbox_inches='tight')
        plt.savefig(f'{save_path}/lr_curve.svg', format='svg', bbox_inches='tight')

    plt.show()

# Plot consfusion matrix
def plot_confusion_matrix(cm, class_names=None, norm=False, cmap=plt.cm.Blues, task='multiclass',
                          figsize=(12, 5), fontsize=16, title=None, save_path=None):

    if cm.ndim != 2 or cm.shape[0] != cm.shape[1]:
        raise ValueError('Confusion matrix must be a 2D square matrix')
    n_classes = cm.shape[0]

    if task == 'binary' and n_classes != 2:
        raise ValueError('For binary classification, the confusion matrix must have shape (2, 2)')

    if class_names is None:
        if task == 'binary':
            class_names = ['Negative', 'Positive']
        else:
            class_names = [f'Class {i}' for i in range(n_classes)]

    if len(class_names) != n_classes:
        raise ValueError(f'Number of class names ({len(class_names)}) does not match the number of classes ({n_classes})')

    cm = cm.astype('float')
    correct = np.trace(cm)
    total = np.sum(cm)
    accuracy = correct / total if total > 0 else 0.0
    misclassified = 1.0 - accuracy

    if norm:
        row_sum = cm.sum(axis=1, keepdims=True)
        row_sum[row_sum == 0] = 1.0
        cm = cm / row_sum

    suffix = ' ' + '(Normalized)' if norm else ''
    plot_title = f'{title}\nConfusion Matrix{suffix}' if title else f'Confusion Matrix{suffix}'

    plt.figure(figsize=figsize)
    plt.imshow(cm, interpolation='nearest', cmap=cmap)
    plt.title(plot_title, fontsize=fontsize)
    plt.colorbar()

    tick_marks = np.arange(n_classes)
    plt.xticks(tick_marks, class_names, rotation=90, fontsize=fontsize)
    plt.yticks(tick_marks, class_names, fontsize=fontsize)

    fmt = '.2f' if norm else '.0f'
    thresh = cm.max() / 2.0 if cm.size else 0.0

    for i, j in itertools.product(range(n_classes), range(n_classes)):
        plt.text(
            j, i,
            format(cm[i, j], fmt),
            ha='center',
            va='center',
            fontsize=fontsize,
            color='white' if cm[i, j] > thresh else 'black'
        )

    plt.ylabel('True label', fontsize=fontsize)
    plt.xlabel(
        f'Predicted label\nAccuracy: {accuracy:.4f} | Misclass: {misclassified:.4f}',
        fontsize=fontsize
    )
    plt.tight_layout()

    if save_path:
        suffix = 'norm' if norm else 'unnorm'
        plt.savefig(f'{save_path}/conf_matrix_{suffix}.png', format='png', dpi=300, bbox_inches='tight')
        plt.savefig(f'{save_path}/conf_matrix_{suffix}.svg', format='svg', bbox_inches='tight')

    plt.show()

def plot_roc_auc_curve(y_true, y_pred_probs, class_names=None, task='multiclass',
                       legend_ncol=1, width_ratios=[3, 1], figsize=(12, 5),
                       fontsize=16, title=None, save_path=None):

    fig, (ax_main, ax_legend) = plt.subplots(1, 2, figsize=figsize, gridspec_kw={'width_ratios': width_ratios})

    if task == 'binary':
        if y_true.ndim != 1:
            raise ValueError('For binary classification, y_true should be a 1D array')

        if y_pred_probs.ndim == 2:
            if y_pred_probs.shape[1] != 2:
                raise ValueError('For binary classification, y_pred_probs should have shape (n_samples, 2)')
            y_score = y_pred_probs[:, 1]
        else:
            y_score = y_pred_probs

        fpr, tpr, _ = roc_curve(y_true, y_score)
        roc_auc = auc(fpr, tpr)
        ax_main.plot(fpr, tpr, lw=3, label=f'ROC curve (AUC = {roc_auc:.4f})')

    else:
        # multiclass
        if y_pred_probs.ndim != 2:
            raise ValueError('For multiclass classification, y_pred_probs should be a 2D array')
        n_classes = y_pred_probs.shape[1]

        if class_names is None:
            class_names = [f'Class {i}' for i in range(n_classes)]

        y_true_bin = label_binarize(y_true, classes=range(n_classes))

        cmap = plt.get_cmap('viridis')
        colors = [cmap(i) for i in np.linspace(0, 0.9, n_classes)]
        for i in range(n_classes):
            fpr, tpr, _ = roc_curve(y_true_bin[:, i], y_pred_probs[:, i])
            roc_auc = auc(fpr, tpr)
            ax_main.plot(fpr, tpr, lw=2, color=colors[i], label=f'{class_names[i]} (AUC = {roc_auc:.4f})')

        fpr_micro, tpr_micro, _ = roc_curve(y_true_bin.ravel(), y_pred_probs.ravel())
        auc_micro = auc(fpr_micro, tpr_micro)
        ax_main.plot(fpr_micro, tpr_micro, linestyle='--', lw=2, color='black',
                     label=f'Micro-average (AUC = {auc_micro:.4f})')

        all_fpr = np.linspace(0, 1, 100)
        mean_tpr = np.zeros_like(all_fpr)
        for i in range(n_classes):
            fpr_i, tpr_i, _ = roc_curve(y_true_bin[:, i], y_pred_probs[:, i])
            mean_tpr += np.interp(all_fpr, fpr_i, tpr_i)

        mean_tpr /= n_classes
        mean_tpr[0] = 0.0
        mean_tpr[-1] = 1.0

        auc_macro = auc(all_fpr, mean_tpr)
        ax_main.plot(all_fpr, mean_tpr, label=f'Macro-average (AUC = {auc_macro:.4f})',
                     color='navy', linestyle=':', lw=3)

    ax_main.plot([0, 1], [0, 1], color='gray', lw=2, linestyle='--', alpha=0.7)

    if title:
        plot_title = f'{title}\nReceiver Operating Characteristic (ROC)'
    else:
        plot_title = 'Receiver Operating Characteristic (ROC)'

    ax_main.set_xlim([0.0, 1.0])
    ax_main.set_ylim([0.0, 1.05])
    ax_main.set_xlabel('False Positive Rate', fontsize=fontsize)
    ax_main.set_ylabel('True Positive Rate', fontsize=fontsize)
    ax_main.set_title(plot_title, fontsize=fontsize)
    ax_main.grid(alpha=0.3)
    ax_main.tick_params(labelsize=fontsize)

    handles, labels = ax_main.get_legend_handles_labels()
    ax_legend.axis('off')
    ax_legend.legend(handles, labels, loc='center left',
                     ncol=legend_ncol, fontsize=fontsize, frameon=False)

    plt.tight_layout()

    if save_path:
        plt.savefig(f'{save_path}/roc_auc_curve.png', format='png', dpi=300, bbox_inches='tight')
        plt.savefig(f'{save_path}/roc_auc_curve.svg', format='svg', bbox_inches='tight')

    plt.show()

# visualize predictions
def vis_preds(df, filepaths_col, true_label_col, pred_label_col, prob_col, seed,
              n_images=7, n_rows=None, target_size=(224, 224),
              figsize=(12, 5), fontsize=16, title=None, save_path=None):

    all_classes = np.sort(df[true_label_col].unique())

    if n_rows is not None and n_rows < len(all_classes):
        classes = all_classes[:n_rows]
    else:
        classes = all_classes
        n_rows = len(classes)

    n_cols = n_images
    fig, axes = plt.subplots(n_rows, n_cols, figsize=(figsize[0], figsize[1] * n_rows))

    axes = np.atleast_2d(axes)
    if axes.shape[0] != n_rows or axes.shape[1] != n_cols:
        axes = axes.reshape(n_rows, n_cols)

    if title:
        fig.suptitle(title, fontsize=fontsize + 4, y=0.92)

    for row_idx, class_name in enumerate(classes):
        df_class = df[df[true_label_col] == class_name].sample(
            n=min(n_images, len(df[df[true_label_col] == class_name])),
            random_state=seed
        ).reset_index(drop=True)

        for col_idx in range(n_cols):
            ax = axes[row_idx, col_idx]
            ax.axis('off')

            if col_idx < len(df_class):
                row = df_class.iloc[col_idx]
                img_path = row[filepaths_col]
                pred_class_name = row[pred_label_col]
                confidence = row[prob_col]
                color = 'green' if class_name == pred_class_name else 'red'

                img = Image.open(img_path).convert('RGB').resize(target_size)
                ax.imshow(img)

                ax.set_title(f'True: {class_name}\nPred: {pred_class_name}\n(Conf: {confidence:.2f})',
                             fontsize=fontsize, color=color)

    plt.tight_layout()
    plt.subplots_adjust(top=1.0 - (0.05 / n_rows))

    if save_path:
        plt.savefig(f'{save_path}/vis_preds.png', dpi=300, bbox_inches='tight')
        plt.savefig(f'{save_path}/vis_preds.svg', bbox_inches='tight')

    plt.show()

# ใช้คู่กับ plot_grad_cam
def preprocess_input(img_path, mean, std, target_size):
    img = cv2.imread(img_path)
    img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    img = cv2.resize(img, target_size)
    raw_img = np.float32(img) / 255.0

    img_tensor = v2.ToImage()(img)
    img_tensor = v2.ToDtype(torch.float32, scale=True)(img_tensor)
    img_tensor = v2.Normalize(mean=mean, std=std)(img_tensor)
    img_tensor = img_tensor.unsqueeze(0)
    return raw_img, img_tensor

def plot_grad_cam(model, conv_layers, df, filepaths_col, true_label_col, true_idx,
                  probs_col, mean, std, target_size=(224, 224), figsize=(20, 5),
                  fontsize=16, title=None, save_path=None):

    '''
        Ref: https://github.com/jacobgil/pytorch-grad-cam
    '''
    cam = GradCAM(model=model, target_layers=conv_layers)
    num_imgs = len(df)

    fig, axes = plt.subplots(nrows=2, ncols=num_imgs, figsize=figsize)

    if num_imgs == 1:
        axes = axes.reshape(2, 1)

    if title:
        fig.suptitle(title, fontsize=fontsize + 4, y=0.92)

    model.eval()

    for i, (idx, row) in enumerate(df.iterrows()):
        img_path = row[filepaths_col]
        true_label = row[true_label_col]
        true_label_idx = int(row[true_idx])
        prob = row[probs_col]

        raw_img, img_tensor = preprocess_input(img_path, mean, std, target_size)

        targets = [ClassifierOutputTarget(true_label_idx)]
        grayscale_cam = cam(input_tensor=img_tensor, targets=targets)
        grayscale_cam = grayscale_cam[0, :]
        visualization = show_cam_on_image(raw_img, grayscale_cam, use_rgb=True)

        # --- Row 1: Original Image ---
        axes[0, i].imshow(raw_img)
        axes[0, i].set_title(true_label, fontsize=fontsize)
        axes[0, i].axis('off')

        # --- Row 2: Grad-CAM Image ---
        axes[1, i].imshow(visualization)
        axes[1, i].axis('off')
        axes[1, i].set_title(f'P = {prob:.5f}', fontsize=fontsize, y=-0.2)

    plt.tight_layout()

    if save_path:
        plt.savefig(f'{save_path}/grad_cam.png', dpi=300, bbox_inches='tight')
        plt.savefig(f'{save_path}/grad_cam.svg', bbox_inches='tight')

    plt.show()

# visualize images
def vis_images(df, filepaths_col, label_col, n_rows=2, n_cols=5,
               target_size=(224, 224), figsize=(15, 6), fontsize=14, title=None, save_path=None):

    total_slots = n_rows * n_cols
    subset = df.iloc[:total_slots]
    total_images = len(subset)

    fig = plt.figure(figsize=figsize)

    if title:
        fig.suptitle(title, fontsize=fontsize + 2, fontweight='bold', y=0.97)

    img_width = 0.15
    img_height = 0.35
    spacing = 0.02

    for r in range(n_rows):
        row_start = r * n_cols
        row_end = min(row_start + n_cols, total_images)
        row_items = row_end - row_start

        if row_items <= 0:
            break

        total_row_width = row_items * img_width + (row_items - 1) * spacing
        start_x = (1.0 - total_row_width) / 2

        y_pos = 0.55 - r * 0.45

        for c in range(row_items):
            idx = row_start + c
            row = subset.iloc[idx]
            img_path = pathlib.Path(row[filepaths_col])

            ax = fig.add_axes([
                start_x + c * (img_width + spacing),
                y_pos,
                img_width,
                img_height
            ])

            img = Image.open(img_path).convert('RGB').resize(target_size)
            ax.imshow(img)

            ax.text(
                0.5, -0.1,
                f'{row[label_col]}',
                fontsize=fontsize,
                ha='center',
                va='center',
                transform=ax.transAxes
            )

            ax.axis('off')

    if save_path:
        plt.savefig(f'{save_path}.png', dpi=300, bbox_inches='tight')
        plt.savefig(f'{save_path}.svg', bbox_inches='tight')

    plt.show()