import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import chi2, binomtest

def _read_csv_or_empty(path):
    try:
        return pd.read_csv(path)
    except pd.errors.EmptyDataError:
        return pd.DataFrame()

def load_predictions(model_dir, prefix='ensem'):
    ensem_dir = os.path.join(model_dir, 'ensemble')
    correct_path = os.path.join(ensem_dir, f"{prefix}_correct_preds.csv")
    incorrect_path = os.path.join(ensem_dir, f"{prefix}_incorrect_preds.csv")
    for path in [correct_path, incorrect_path]:
        if not os.path.exists(path):
            raise FileNotFoundError(f"[Error] Prediction records not found: {path}")

    df = pd.concat([_read_csv_or_empty(correct_path), _read_csv_or_empty(incorrect_path)], ignore_index=True)
    if df['Filepaths'].duplicated().any():
        raise ValueError(f"[Error] Duplicated Filepaths found in {ensem_dir}")

    df = df.set_index('Filepaths')[['True_Index', 'True_Label', 'Pred_Index', 'Pred_Label']]
    print(f"[*] Loaded {len(df)} predictions from {ensem_dir}")
    return df

def align_predictions(df_baseline, df_proposed):
    only_baseline = df_baseline.index.difference(df_proposed.index)
    only_proposed = df_proposed.index.difference(df_baseline.index)
    if len(only_baseline) or len(only_proposed):
        raise ValueError(f"[Error] Test samples are not identical: {len(only_baseline)} only in baseline, "
                         f"{len(only_proposed)} only in proposed. e.g. {list(only_baseline[:2]) + list(only_proposed[:2])}")

    df_proposed = df_proposed.loc[df_baseline.index]
    if not np.array_equal(df_baseline['True_Index'].values, df_proposed['True_Index'].values):
        raise ValueError("[Error] True labels of the two models do not match on the same test samples.")

    df = pd.DataFrame({
        'Filepaths': df_baseline.index,
        'True_Index': df_baseline['True_Index'].values,
        'True_Label': df_baseline['True_Label'].values,
        'Baseline_Pred_Index': df_baseline['Pred_Index'].values,
        'Baseline_Pred_Label': df_baseline['Pred_Label'].values,
        'Proposed_Pred_Index': df_proposed['Pred_Index'].values,
        'Proposed_Pred_Label': df_proposed['Pred_Label'].values,
    })
    df['Baseline_Correct'] = df['Baseline_Pred_Index'] == df['True_Index']
    df['Proposed_Correct'] = df['Proposed_Pred_Index'] == df['True_Index']
    return df.sort_values('Filepaths').reset_index(drop=True)

def mcnemar_test(baseline_correct, proposed_correct, alpha=0.05):
    """
        McNemar's test with continuity correction.
        Args:
            - baseline_correct (np.array): Boolean array, True if the baseline predicts the sample correctly
            - proposed_correct (np.array): Boolean array, True if the proposed model predicts the sample correctly
            - alpha (float): Significance level (Default is 0.05)
        Returns:
            - result (dict): Contingency counts, chi-square statistic, p-values and decision
    """
    baseline_correct = np.asarray(baseline_correct, dtype=bool)
    proposed_correct = np.asarray(proposed_correct, dtype=bool)

    both_correct = int(np.sum(proposed_correct & baseline_correct))
    b = int(np.sum(proposed_correct & ~baseline_correct))
    c = int(np.sum(~proposed_correct & baseline_correct))
    both_incorrect = int(np.sum(~proposed_correct & ~baseline_correct))

    if b + c == 0:
        chi2_stat, p_value, exact_p_value = 0.0, 1.0, 1.0
    else:
        chi2_stat = (abs(b - c) - 1) ** 2 / (b + c)
        p_value = float(chi2.sf(chi2_stat, df=1))
        exact_p_value = float(binomtest(b, b + c, 0.5, alternative='two-sided').pvalue)

    return {
        'both_correct': both_correct,
        'b': b,
        'c': c,
        'both_incorrect': both_incorrect,
        'chi2': chi2_stat,
        'p_value': p_value,
        'exact_p_value': exact_p_value,
        'alpha': alpha,
        'reject_h0': p_value < alpha,
    }

def plot_mcnemar_contingency(result, baseline_name='Baseline', proposed_name='Proposed', cmap=plt.cm.YlGnBu,
                             figsize=(10, 8), fontsize=14, annot_fontsize=None, title=None, save_path=None):
    """
        For plotting and visualization the McNemar's contingency table (Rows: proposed, Columns: baseline).
        Args:
            - result (dict): Output of mcnemar_test
            - baseline_name (str): Name of the baseline model
            - proposed_name (str): Name of the proposed model
            - cmap (matplotlib.colors.Colormap): Optional, the colormap to use.
            - figsize (tuple): Optional, the size of the figure.
            - fontsize (int): Optional, the size of the font (title, axis labels, ticks).
            - annot_fontsize (int): Optional, the size of the font inside the cells. Defaults to fontsize - 2.
            - title (str): Optional, the title of the figure.
            - save_path (str): Optional, the directory to save the figure.
        Returns:
            - None
    """
    if annot_fontsize is None:
        annot_fontsize = max(fontsize - 2, 1)

    counts = np.array([[result['both_correct'], result['b']],
                       [result['c'], result['both_incorrect']]], dtype=float)
    cell_text = [
        [f"Both Correct\n{result['both_correct']}",
         f"{proposed_name} Correct\n{baseline_name} Incorrect\n(b = {result['b']})"],
        [f"{proposed_name} Incorrect\n{baseline_name} Correct\n(c = {result['c']})",
         f"Both Incorrect\n{result['both_incorrect']}"],
    ]

    plt.figure(figsize=figsize)
    plt.imshow(counts, interpolation='nearest', cmap=cmap)
    cbar = plt.colorbar()
    cbar.ax.tick_params(labelsize=fontsize)

    thresh = counts.max() / 2.0
    for i in range(2):
        for j in range(2):
            plt.text(j, i, cell_text[i][j], ha='center', va='center', fontsize=annot_fontsize, fontweight='bold',
                     color='white' if counts[i, j] > thresh else 'black')

    # Model names are already in the axis labels, so the ticks only show the outcome
    plt.xticks([0, 1], ['Correct', 'Incorrect'], fontsize=fontsize)
    plt.yticks([0, 1], ['Correct', 'Incorrect'], fontsize=fontsize, rotation=90, va='center')
    plt.xlabel(f'{baseline_name} Prediction', fontsize=fontsize)
    plt.ylabel(f'{proposed_name} Prediction', fontsize=fontsize)

    stat_text = (f"$\\chi^2$ = {result['chi2']:.4f} | p = {result['p_value']:.4g} | "
                 f"Exact p = {result['exact_p_value']:.4g}")
    plot_title = f"{title} - McNemar's Test" if title else "McNemar's Test"
    plt.title(f"{plot_title}\n{stat_text}", fontsize=fontsize)
    plt.tight_layout()

    if save_path:
        plt.savefig(f'{save_path}/mcnemar_contingency.png', format='png', dpi=300, bbox_inches='tight')
        plt.savefig(f'{save_path}/mcnemar_contingency.svg', format='svg', bbox_inches='tight')

    plt.show()

def compare_mcnemar(baseline_model_dir, proposed_model_dir, baseline_name='Baseline', proposed_name='Proposed',
                    alpha=0.05, prefix='ensem', title=None, cmap=plt.cm.YlGnBu, figsize=(10, 8), fontsize=14,
                    annot_fontsize=None, plot=True):
    """
        This function runs McNemar's test between a baseline and a proposed model on the same test set.

        Args:
            - baseline_model_dir (str): Base directory of the baseline experiment
            - proposed_model_dir (str): Base directory of the proposed experiment
            - baseline_name (str): Name of the baseline model (e.g. 'ConvNeXt-T')
            - proposed_name (str): Name of the proposed model
            - alpha (float): Significance level (Default is 0.05)
            - prefix (str): Prefix of the prediction records (Default is 'ensem')
            - title (str): Title prefix of the figure (Optional) e.g. 'MushroomA Dataset'
            - cmap (matplotlib.colors.Colormap): Colormap of the contingency table
            - figsize (tuple): Figure size of the contingency table
            - fontsize (int): Font size of the figure (title, axis labels, ticks)
            - annot_fontsize (int): Font size inside the cells (Optional). Defaults to fontsize - 2
            - plot (bool): Whether to plot and save the contingency table (Default is True)
        Returns:
            - result_df (pd.DataFrame): Summary of McNemar's test
            - df_aligned (pd.DataFrame): Aligned per-sample predictions of both models

        Output directory tree
        - proposed_model_dir
            |- ensemble_addition
                |- mcnemar
                    |- mcnemar_test_result.csv
                    |- mcnemar_contingency_table.csv
                    |- mcnemar_disagreements.csv
                    |- mcnemar_contingency (.png, .svg)
    """
    df_baseline = load_predictions(baseline_model_dir, prefix)
    df_proposed = load_predictions(proposed_model_dir, prefix)
    df_aligned = align_predictions(df_baseline, df_proposed)
    n_samples = len(df_aligned)
    print(f"[*] Aligned {n_samples} test samples (Filepaths and true labels verified)")

    result = mcnemar_test(df_aligned['Baseline_Correct'].values, df_aligned['Proposed_Correct'].values, alpha=alpha)

    baseline_acc = df_aligned['Baseline_Correct'].mean()
    proposed_acc = df_aligned['Proposed_Correct'].mean()

    save_dir = os.path.join(proposed_model_dir, 'ensemble_addition', 'mcnemar')
    os.makedirs(save_dir, exist_ok=True)

    result_df = pd.DataFrame([{
        'Baseline': baseline_name,
        'Proposed': proposed_name,
        'N': n_samples,
        'Baseline Accuracy': baseline_acc,
        'Proposed Accuracy': proposed_acc,
        'Accuracy Diff (pp)': (proposed_acc - baseline_acc) * 100.0,
        'Both Correct': result['both_correct'],
        'b (Proposed Correct, Baseline Incorrect)': result['b'],
        'c (Proposed Incorrect, Baseline Correct)': result['c'],
        'Both Incorrect': result['both_incorrect'],
        'Chi-square': result['chi2'],
        'p-value': result['p_value'],
        'Exact p-value': result['exact_p_value'],
        'Alpha': alpha,
        'Significant': result['reject_h0'],
    }])
    result_path = os.path.join(save_dir, 'mcnemar_test_result.csv')
    result_df.to_csv(result_path, index=False)

    contingency_df = pd.DataFrame(
        [[result['both_correct'], result['b']], [result['c'], result['both_incorrect']]],
        index=[f'{proposed_name} Correct', f'{proposed_name} Incorrect'],
        columns=[f'{baseline_name} Correct', f'{baseline_name} Incorrect']
    )
    contingency_df.to_csv(os.path.join(save_dir, 'mcnemar_contingency_table.csv'))

    df_disagree = df_aligned[df_aligned['Baseline_Correct'] != df_aligned['Proposed_Correct']]
    df_disagree.to_csv(os.path.join(save_dir, 'mcnemar_disagreements.csv'), index=False)

    print(f"\n{'-'*100}")
    print(f"McNemar's Test: {proposed_name} vs {baseline_name} (N = {n_samples})")
    print(contingency_df.to_string())
    print(f"\nChi-square = {result['chi2']:.4f} | p-value = {result['p_value']:.4g} | Exact p-value = {result['exact_p_value']:.4g}")
    decision = 'Reject H0 (significant difference)' if result['reject_h0'] else 'Fail to reject H0 (no significant difference)'
    print(f"alpha = {alpha} -> {decision}")
    print(f"{'-'*100}")
    print(f"[Logs] Saved McNemar's Test Results to: {save_dir}")

    if plot:
        plot_mcnemar_contingency(
            result=result,
            baseline_name=baseline_name,
            proposed_name=proposed_name,
            cmap=cmap,
            figsize=figsize,
            fontsize=fontsize,
            annot_fontsize=annot_fontsize,
            title=title,
            save_path=save_dir
        )

    return result_df, df_aligned